mod get_access_token;
mod login;
mod logout;

use async_trait::async_trait;
use std::str::FromStr;

use get_access_token::GetAccessToken;
use login::Login;
use logout::Logout;

use crate::{
    cmd_uri::CmdUri,
    component::{AzCmd, AzCmdGroup, AzComponent, AzComponentCtx},
    error::{AzError, AzInternalError},
    pb::{
        cmd_interface, execute_response, CmdComponent, CmdHelp, CmdInterface, CmdOutputFormat,
        CmdParams, ComponentMetadata, ExecuteRequest, ExecuteResponse, InterfaceRequest,
        InterfaceResponse, MetadataRequest, MetadataResponse, ValidateRequest, ValidateResponse,
    },
    VERSION,
};

/// The built-in component for managing the account
#[derive(Debug, Default)]
pub struct AccountComponent {}

// should be generated by component macro later
#[async_trait]
impl AzCmdGroup for AccountComponent {
    const URI: &'static str = "cmd://azure/account/";

    fn cmd_interface(depth: Option<u32>) -> CmdInterface {
        let groups = vec![];
        let mut commands = vec![];
        if depth.is_none_or(|d| d > 0) {
            let depth = depth.map(|d| d - 1);
            commands.push(GetAccessToken::cmd_interface(depth));
            commands.push(Login::cmd_interface(depth));
            commands.push(Logout::cmd_interface(depth));
        }
        CmdInterface {
            name: "account".to_string(),
            help: Some(CmdHelp {
                short: "Manage Azure subscription information.".to_string(),
                long: None,
            }),
            uri: Self::uri().to_string(),
            level: Some(cmd_interface::Level::Component(CmdComponent {
                version: VERSION.to_string(),
                groups,
                commands,
            })),
        }
    }

    fn get_interface(
        depth: Option<u32>,
        mut segments: impl Iterator<Item = String>,
    ) -> Option<CmdInterface> {
        match segments.next().as_deref() {
            None => Some(Self::cmd_interface(depth)),
            Some("get-access-token") => Some(GetAccessToken::cmd_interface(depth)),
            Some("login") => Some(Login::cmd_interface(depth)),
            Some("logout") => Some(Logout::cmd_interface(depth)),
            _ => None,
        }
    }

    fn resolve_cmd_uri(mut segments: impl Iterator<Item = String>) -> Option<CmdUri> {
        match segments.next().as_deref() {
            None => Some(Self::uri()),
            Some("get-access-token") => Some(GetAccessToken::uri()),
            Some("login") => Some(Login::uri()),
            Some("logout") => Some(Logout::uri()),
            _ => None,
        }
    }

    async fn execute_group<T: AzComponentCtx>(
        ctx: &T,
        mut segments: impl Iterator<Item = String> + Send,
        params: Option<CmdParams>,
        output_format: Option<CmdOutputFormat>,
    ) -> Result<execute_response::Data, AzError> {
        match segments.next().as_deref() {
            Some("get-access-token") => GetAccessToken::execute(ctx, params, output_format).await,
            Some("login") => Login::execute(ctx, params, output_format).await,
            Some("logout") => Logout::execute(ctx, params, output_format).await,
            Some(other) => Err(AzInternalError::InvalidCmdUriError(other.to_string()).into()),
            None => Err(AzInternalError::InvalidCmdUriError(Self::uri().to_string()).into()),
        }
    }
}

#[async_trait]
impl<T: AzComponentCtx> AzComponent<T> for AccountComponent {
    async fn metadata(&self, _: &T, _: MetadataRequest) -> Result<MetadataResponse, AzError> {
        let interface = Self::cmd_interface(Some(0));
        Ok(MetadataResponse {
            metadata: Some(ComponentMetadata {
                name: interface.name,
                version: VERSION.to_string(),
                uri: interface.uri,
                help: interface.help,
            }),
        })
    }

    async fn interface(
        &self,
        _: &T,
        request: InterfaceRequest,
    ) -> Result<InterfaceResponse, AzError> {
        let skip = Self::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let depth = match request.depth {
            0 => None, // None means all the depth
            _ => Some(request.depth),
        };
        let segments = cmd_uri.segments().skip(skip).map(|s| s.to_string());
        let interface = Self::get_interface(depth, segments);
        Ok(InterfaceResponse { interface })
    }

    async fn execute(&self, ctx: &T, request: ExecuteRequest) -> Result<ExecuteResponse, AzError> {
        let skip = Self::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let segments = cmd_uri.segments().skip(skip).map(|s| s.to_string());
        let result =
            Self::execute_group(ctx, segments, request.params, request.output_format).await?;
        Ok(ExecuteResponse { data: Some(result) })
    }

    async fn validate(&self, _: &T, request: ValidateRequest) -> Result<ValidateResponse, AzError> {
        let skip = Self::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let segments = cmd_uri.segments().skip(skip).map(|s| s.to_string());
        let uri = Self::resolve_cmd_uri(segments).map(|u| {
            // add version and params from the cmd_uri
            let mut uri = u.with_version(VERSION);
            for (key, value) in cmd_uri.params() {
                uri = uri.with_param_values(key, value.collect::<Vec<_>>());
            }
            uri.to_string()
        });
        Ok(ValidateResponse { uri })
    }
}
