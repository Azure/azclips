#[derive(Debug, Default)]
pub struct Login {
    scope: Option<Vec<String>>,
    tenant_id: Option<String>,
    username: Option<String>,
    password: Option<String>,
    use_device_code: bool,
    allow_no_subscriptions: bool,
    service_principal: bool,
    identity: bool,
    client_id: Option<String>,
    object_id: Option<String>,
    resource_id: Option<String>,
    certificate_path: Option<String>,
    user_cert_sn_issuer: bool,
    federated_token: Option<String>,
}

#[async_trait]
impl AzCommandExecute for Login {
    type Output = String;

    async fn run<T: AzComponentCtx>(&self, _: &T) -> Result<Option<Self::Output>, AzError> {
        println!("login");
        println!("scope: {:?}", self.scope);
        println!("tenant_id: {:?}", self.tenant_id);

        let interactive: bool = self.username.is_none();
        let mut use_device_code = self.use_device_code;

        // Todo: Set arm_scope for different clouds
        let arm_scope = "https://management.core.windows.net/.default";
        let scopes = match &self.scope {
            Some(s) => s.iter().map(|s| s.as_str()).collect::<Vec<&str>>(),
            None => vec![arm_scope],
        };
        let tenant_id = self.tenant_id.as_deref().unwrap_or("organizations");

        // Todo: Set authority_url for different clouds

        if interactive {
            if !use_device_code && !can_launch_browser() {
                println!("No web browser is available. Falling back to device code.");
                use_device_code = true;
            }
            if use_device_code {
                self.login_with_device_code().map_err(AzError::from)?;
            } else {
                self.login_with_auth_code(&scopes, tenant_id).await?;
            }
        } else {
            // Todo: Implement non-interactive login logic
            println!("Logging in non-interactively...");
        }

        Ok(None)
    }
}

impl Login {
    async fn login_with_auth_code(
        &self,
        scopes: &[&str],
        tenant_id: &str,
    ) -> Result<(), AuthenticationError> {
        println!("Logging in interactively...");

        let mut user_credential =
            UserCredential::new(None, None, None, Some(tenant_id.to_string()));
        let token = user_credential.acquire_token(scopes).await?;

        println!("Login successful with user: {:?}", user_credential.username);

        // Set current user as the default user in token cache with method set_default_account
        if let (Some(home_account_id), Some(environment)) = (
            &user_credential.home_account_id,
            &user_credential.environment,
        ) {
            if let Some(cache_path) = get_default_token_cache_path() {
                match FilePersistentTokenCache::new(cache_path) {
                    Ok(token_cache) => {
                        if let Err(e) = token_cache.cache().set_default_account(
                            Some(home_account_id.as_str()),
                            Some(environment.as_str()),
                            user_credential.tenant_id.as_deref(),
                        ) {
                            error!("Failed to set default account in token cache: {}", e);
                        } else {
                            // Save changes to the token cache
                            if let Err(e) = token_cache.save_if_changed() {
                                error!("Failed to save token cache changes: {}", e);
                            }
                        }
                    }
                    Err(e) => {
                        error!("Failed to access token cache: {}", e);
                    }
                }
            }
        }

        println!(
            "Token acquired successfully. Token expires on: {}\n",
            format_token_expires_on_readable(token.expires_on.unix_timestamp() as u64)
        );
        Ok(())
    }

    fn login_with_device_code(&self) -> Result<(), AuthenticationError> {
        // Todo: Login with device code
        println!("Logging in with device code...");
        Ok(())
    }
}

