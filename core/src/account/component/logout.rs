use async_trait::async_trait;
use tracing::error;

use crate::{
    component::{AzCommand, AzCommandExecute, AzComponentCtx},
    error::AzError,
    pb::{
        cmd_arg, cmd_interface, cmd_string_arg, CmdArg, CmdArgHelp, CmdCommand, CmdHelp,
        CmdInterface, CmdParams, CmdStringArg, CmdStringFormat,
    },
    VERSION,
};

#[derive(Debug, Default)]
pub struct Logout {
    username: Option<String>,
}

#[async_trait]

impl AzCommandExecute for Logout {
    type Output = String;

    async fn run<T: AzComponentCtx>(&self, _: &T) -> Result<Option<Self::Output>, AzError> {
        println!("logout");
        println!("username: {:?}", self.username);
        Ok(Some("logout success".to_string()))
    }
}

// will be generated by command macro
impl AzCommand for Logout {
    const URI: &'static str = "cmd://azure/account/logout";

    fn build_interface(_: Option<u32>) -> CmdInterface {
        CmdInterface {
            level: Some(cmd_interface::Level::Command(CmdCommand {
                name: "logout".to_string(),
                uri: Self::uri().to_string(),
                version: VERSION.to_string(),
                help: Some(CmdHelp {
                    short: "Log out to remove access to Azure subscriptions.".to_string(),
                    ..Default::default()
                }),
                args: Self::args(),
                positional_args: vec![],
            })),
        }
    }

    fn args() -> Vec<CmdArg> {
        vec![CmdArg {
            var_name: "username".to_string(),
            name: "username".to_string(),
            options: vec!["username".to_string()],
            help: Some(CmdArgHelp {
                short: "The username to log out from Azure.".to_string(),
                ..Default::default()
            }),
            arg_type: Some(cmd_arg::ArgType::String(CmdStringArg {
                format: Some(cmd_string_arg::Format::String(CmdStringFormat::default())),
                ..Default::default()
            })),
            ..Default::default()
        }]
    }

    fn try_from(params: Option<CmdParams>) -> Result<Self, AzError> {
        let mut logout = Self::default();
        if let Some(params) = params {
            for (name, v) in params.params.iter() {
                match name.as_str() {
                    "username" => {
                        logout.username = serde_json::from_slice(v).expect("failed to parse json")
                    }
                    _ => {
                        error!("unknown argument: {}", name);
                    }
                }
            }
        }
        Ok(logout)
    }
}
