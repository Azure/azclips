use std::str::FromStr;

use serde_json::Value;
use tracing::error;

use crate::{
    cmd_uri::CmdUri,
    component::AzComponentCtx,
    error::AzError,
    pb::command::{
        cmd_arg, cmd_interface, cmd_string_arg, CmdArg, CmdArgHelp, CmdCommand, CmdHelp,
        CmdInterface, CmdParams, CmdStringArg, CmdStringFormat,
    },
    VERSION,
};

#[derive(Debug, Default)]
pub(super) struct ListClouds {}

impl ListClouds {
    pub(super) async fn run<T: AzComponentCtx>(&self, _: &T) -> Result<Option<Value>, AzError> {
        Ok(Some(Value::String("list clouds".to_string())))
    }
}

// will be generated by command macro later
impl ListClouds {
    const URI: &'static str = "cmd://azure/cloud/list";

    pub fn uri() -> CmdUri {
        CmdUri::from_str(Self::URI).unwrap()
    }

    pub fn get_cmd_interface() -> CmdInterface {
        CmdInterface {
            name: "list".to_string(),
            help: Some(CmdHelp {
                short: "List registered clouds.".to_string(),
                long: None,
            }),
            uri: Self::uri().to_string(),
            level: Some(cmd_interface::Level::Command(CmdCommand {
                version: VERSION.to_string(),
                args: Self::args(),
                positional_args: vec![],
            })),
        }
    }

    fn args() -> Vec<CmdArg> {
        vec![]
    }

    pub fn try_from(params: &Option<CmdParams>) -> Result<Self, AzError> {
        Ok(Self::default())
    }
}
