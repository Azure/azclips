use async_trait::async_trait;
use tracing::error;

use crate::{
    component::{AzCmd, AzCmdExecute, AzComponentCtx},
    config::cloud::AzCloudMetadata,
    error::AzError,
    pb::command::{
        cmd_arg, cmd_interface, CmdArg, CmdArgHelp, CmdCommand, CmdHelp, CmdInterface, CmdParams,
        CmdStringArg,
    },
    AzCloud, AzCore, VERSION,
};

#[derive(Debug, Default)]
pub(super) struct ActivateCloud {
    name: AzCloud,
}

#[async_trait]
impl AzCmdExecute for ActivateCloud {
    type Output = AzCloudMetadata;

    async fn run<T: AzComponentCtx>(&self, ctx: &T) -> Result<Option<Self::Output>, AzError> {
        let core = AzCore::instance().await;
        core.switch_cloud(&self.name).await?;
        let cfg = ctx.get_cfg().await;
        Ok(Some(cfg.clouds.get_active().to_owned()))
    }
}

// will be generated by command macro later
impl AzCmd for ActivateCloud {
    const URI: &'static str = "cmd://azure/config/cloud/activate";

    fn cmd_interface(_: Option<u32>) -> CmdInterface {
        CmdInterface {
            name: "activate".to_string(),
            help: Some(CmdHelp {
                short: "activate a cloud.".to_string(),
                long: None,
            }),
            uri: Self::uri().to_string(),
            level: Some(cmd_interface::Level::Command(CmdCommand {
                version: VERSION.to_string(),
                args: Self::args(),
                positional_args: vec![],
            })),
        }
    }

    fn args() -> Vec<CmdArg> {
        vec![CmdArg {
            name: "name".to_string(),
            help: Some(CmdArgHelp {
                short: "The name of the cloud to activate.".to_string(),
                long: None,
            }),
            options: vec!["name".to_string()],
            required: true,
            arg_type: Some(cmd_arg::ArgType::Str(CmdStringArg {
                // format: Some(CmdStringFormat::Enum(vec!["name".to_string()])),
                ..Default::default()
            })),
            ..Default::default()
        }]
    }

    fn try_from(params: Option<CmdParams>) -> Result<Self, AzError> {
        let mut activate_cloud = Self::default();
        if let Some(params) = params {
            for (name, v) in params.params.iter() {
                match name.as_str() {
                    "name" => {
                        activate_cloud.name = serde_json::from_slice::<String>(v)
                            .expect("failed to parse json")
                            .parse()
                            .expect("failed to convert to AzCloud");
                    }
                    _ => {
                        error!("unknown argument: {}", name);
                    }
                }
            }
        }
        Ok(activate_cloud)
    }
}
