use std::str::FromStr;

use async_trait::async_trait;
use serde_json::Value;
use tracing::error;

use crate::{
    cmd_uri::CmdUri,
    component::{
        cmd::{AzCmd, AzCmdExecute},
        AzComponentCtx,
    },
    error::AzError,
    pb::command::{
        cmd_arg, cmd_interface, cmd_string_arg, CmdArg, CmdArgHelp, CmdCommand, CmdHelp,
        CmdInterface, CmdParams, CmdStringArg, CmdStringFormat,
    },
    VERSION,
};

#[derive(Debug, Default)]
pub(super) struct ListClouds {}

#[async_trait]
impl AzCmdExecute for ListClouds {
    type Output = Value;

    async fn run<T: AzComponentCtx>(&self, _: &T) -> Result<Option<Self::Output>, AzError> {
        Ok(Some(Value::String("list clouds".to_string())))
    }
}

// will be generated by command macro later
impl AzCmd for ListClouds {
    const URI: &'static str = "cmd://azure/config/cloud/list";

    fn cmd_interface(_: Option<u32>) -> CmdInterface {
        CmdInterface {
            name: "list".to_string(),
            help: Some(CmdHelp {
                short: "List registered clouds.".to_string(),
                long: None,
            }),
            uri: Self::uri().to_string(),
            level: Some(cmd_interface::Level::Command(CmdCommand {
                version: VERSION.to_string(),
                args: Self::args(),
                positional_args: vec![],
            })),
        }
    }

    fn args() -> Vec<CmdArg> {
        vec![]
    }

    fn try_from(_: Option<CmdParams>) -> Result<Self, AzError> {
        Ok(Self::default())
    }
}
