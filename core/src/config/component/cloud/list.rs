use async_trait::async_trait;

use crate::{
    component::{
        cmd::{AzCmd, AzCmdExecute},
        AzComponentCtx,
    },
    config::cloud::{endpoint, resource_id, AzCloudMetadata},
    error::AzError,
    pb::command::{cmd_interface, CmdArg, CmdCommand, CmdHelp, CmdInterface, CmdParams},
    AzCloud, VERSION,
};

#[derive(Debug, Default)]
pub(super) struct ListClouds {}

#[async_trait]
impl AzCmdExecute for ListClouds {
    type Output = Vec<AzCloudMetadata>;

    async fn run<T: AzComponentCtx>(&self, ctx: &T) -> Result<Option<Self::Output>, AzError> {
        let cfg = ctx.get_cfg().await;
        let mut result = vec![];
        let builtin_clouds = AzCloud::list_builtin();
        builtin_clouds.iter().for_each(|cloud| {
            let cloud_metadata = cfg.cloud.get_cloud(&cloud).unwrap();
            result.push(cloud_metadata);
        });
        for cloud in cfg.cloud.clouds.keys() {
            if !builtin_clouds.contains(cloud) {
                let cloud_metadata = cfg.cloud.get_cloud(&cloud).unwrap();
                result.push(cloud_metadata.clone());
            }
        }
        endpoint::ATTESTATION;
        resource_id::ATTESTATION;
        Ok(Some(result))
    }
}

// will be generated by command macro later
impl AzCmd for ListClouds {
    const URI: &'static str = "cmd://azure/config/cloud/list";

    fn cmd_interface(_: Option<u32>) -> CmdInterface {
        CmdInterface {
            name: "list".to_string(),
            help: Some(CmdHelp {
                short: "List registered clouds.".to_string(),
                long: None,
            }),
            uri: Self::uri().to_string(),
            level: Some(cmd_interface::Level::Command(CmdCommand {
                version: VERSION.to_string(),
                args: Self::args(),
                positional_args: vec![],
            })),
        }
    }

    fn args() -> Vec<CmdArg> {
        vec![]
    }

    fn try_from(_: Option<CmdParams>) -> Result<Self, AzError> {
        Ok(Self::default())
    }
}
