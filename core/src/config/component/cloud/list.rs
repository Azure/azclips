use async_trait::async_trait;

use crate::{
    component::{AzCommand, AzCommandExecute, AzComponentCtx},
    config::cloud::{AzCloud, AzCloudMetadata},
    error::AzError,
    pb::{crs_interface, CrsArg, CrsCommand, CrsHelp, CrsInterface, CrsParams},
    VERSION,
};

#[derive(Debug, Default)]
pub struct ListClouds {}

#[async_trait]
impl AzCommandExecute for ListClouds {
    type Output = Vec<AzCloudMetadata>;

    async fn run<T: AzComponentCtx>(&self, ctx: &T) -> Result<Option<Self::Output>, AzError> {
        let cfg = ctx.get_cfg().await;
        let mut result = vec![];
        let builtin_clouds = AzCloud::list_builtin();
        builtin_clouds.iter().for_each(|cloud| {
            let cloud_metadata = cfg.clouds.get_cloud(cloud).unwrap();
            result.push(cloud_metadata);
        });
        for cloud in cfg.clouds.0.keys() {
            if !builtin_clouds.contains(cloud) {
                let cloud_metadata = cfg.clouds.get_cloud(cloud).unwrap();
                result.push(cloud_metadata.clone());
            }
        }
        Ok(Some(result))
    }
}

// will be generated by command macro later
impl AzCommand for ListClouds {
    const URI: &'static str = "cmd://azure/config/cloud/list";

    fn build_interface(_: Option<u32>) -> CrsInterface {
        CrsInterface {
            level: Some(crs_interface::Level::Command(CrsCommand {
                name: "list".to_string(),
                uri: Self::uri().to_string(),
                version: VERSION.to_string(),
                help: Some(CrsHelp {
                    short: "List registered clouds.".to_string(),
                    long: None,
                }),
                args: Self::args(),
                positional_args: vec![],
            })),
        }
    }

    fn args() -> Vec<CrsArg> {
        vec![]
    }

    fn try_from(_: Option<CrsParams>) -> Result<Self, AzError> {
        Ok(Self::default())
    }
}
