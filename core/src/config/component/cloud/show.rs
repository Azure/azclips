use std::str::FromStr;

use async_trait::async_trait;
use tracing::error;

use crate::{
    component::{
        cmd::{AzCmd, AzCmdExecute},
        AzComponentCtx,
    },
    config::cloud::AzCloudMetadata,
    error::AzError,
    pb::command::{
        cmd_arg, cmd_interface, CmdArg, CmdArgHelp, CmdCommand, CmdHelp, CmdInterface, CmdParams,
        CmdStringArg,
    },
    AzCloud, VERSION,
};

#[derive(Debug, Default)]
pub(super) struct ShowCloud {
    name: String,
}

#[async_trait]
impl AzCmdExecute for ShowCloud {
    type Output = AzCloudMetadata;

    async fn run<T: AzComponentCtx>(&self, ctx: &T) -> Result<Option<Self::Output>, AzError> {
        let cfg = ctx.get_cfg().await;
        let name = AzCloud::from_str(&self.name).unwrap();
        let cloud = cfg.cloud.get_cloud(&name)?;
        Ok(Some(cloud))
    }
}

// will be generated by command macro later
impl AzCmd for ShowCloud {
    const URI: &'static str = "cmd://azure/config/cloud/show";

    fn cmd_interface(_: Option<u32>) -> CmdInterface {
        CmdInterface {
            name: "show".to_string(),
            help: Some(CmdHelp {
                short: "Get the details of a registered cloud.".to_string(),
                long: None,
            }),
            uri: Self::uri().to_string(),
            level: Some(cmd_interface::Level::Command(CmdCommand {
                version: VERSION.to_string(),
                args: Self::args(),
                positional_args: vec![],
            })),
        }
    }

    fn args() -> Vec<CmdArg> {
        vec![CmdArg {
            name: "name".to_string(),
            help: Some(CmdArgHelp {
                short: "Name of a registered cloud.".to_string(),
                long: None,
            }),
            options: vec!["name".to_string()],
            required: true,
            nullable: false,
            arg_type: Some(cmd_arg::ArgType::Str(CmdStringArg {
                // format: Some(CmdStringFormat::Enum(vec!["name".to_string()])),
                ..Default::default()
            })),
            ..Default::default()
        }]
    }

    fn try_from(params: Option<CmdParams>) -> Result<Self, AzError> {
        let mut show_cloud = Self::default();
        if let Some(params) = params {
            for (name, v) in params.params.iter() {
                match name.as_str() {
                    "name" => {
                        show_cloud.name = serde_json::from_slice(v).expect("failed to parse json");
                    }
                    _ => {
                        error!("unknown argument: {}", name);
                    }
                }
            }
        }
        Ok(show_cloud)
    }
}
