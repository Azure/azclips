use async_trait::async_trait;
use serde_json::Value;
use tracing::error;

use crate::{
    component::{AzCommand, AzCommandExecute, AzComponentCtx},
    error::AzError,
    pb::{
        crs_arg, crs_string_arg, CrsArg, CrsArgHelp, CrsCommand, CrsHelp, CrsParams, CrsStringArg,
        CrsStringFormat,
    },
    VERSION,
};

#[derive(Debug, Default)]
pub struct GetConfig {
    key: Option<String>,
}

#[async_trait]
impl AzCommandExecute for GetConfig {
    type Output = Value;

    async fn run<T: AzComponentCtx>(&self, ctx: &T) -> Result<Option<Self::Output>, AzError> {
        // TODO apply patch keys to get internal properties
        let cfg = ctx.get_cfg().await;
        if let Some(key) = &self.key {
            let value = cfg.settings.get(key);
            if let Some(value) = value {
                Ok(Some(value.clone()))
            } else {
                Ok(None)
            }
        } else {
            Ok(Some(Value::Object(cfg.settings.clone())))
        }
    }
}

// TODO move it to "crs://azure/config/settings/get"
// will be generated by command macro later
impl AzCommand for GetConfig {
    const URI: &'static str = "crs://azure/config/get";

    fn build_interface(_: Option<u32>) -> CrsCommand {
        CrsCommand {
            name: "get".to_string(),
            uri: Self::uri().to_string(),
            version: VERSION.to_string(),
            help: Some(CrsHelp {
                short: "Get a configuration value".to_string(),
                long: None,
            }),
            args: Self::args(),
            positional_args: vec!["key".to_string()],
        }
    }

    fn args() -> Vec<CrsArg> {
        vec![CrsArg {
            // var_name, we cannot build an expression to retrieve the key value when it could be any of the dictionary keys
            name: "key".to_string(),
            options: vec!["key".to_string()],
            help: Some(CrsArgHelp {
                short: "The configuration to get.".to_string(),
                long: Some(" If not provided, all sections and configurations will be listed. If `section` is provided, all configurations under the section will be listed. If `<section>.<key>` is provided, only the corresponding configuration is shown.".to_string())
            }),
            arg_type: Some(crs_arg::ArgType::String(CrsStringArg {
                format: Some(crs_string_arg::Format::String(CrsStringFormat::default())),
                ..Default::default()
            })),
            ..Default::default()
        }]
    }

    fn try_from(params: Option<CrsParams>) -> Result<Self, AzError> {
        let mut get = Self::default();
        if let Some(params) = params {
            for (name, v) in params.params.iter() {
                match name.as_str() {
                    "key" => get.key = serde_json::from_slice(v).expect("failed to parse json"),
                    _ => {
                        error!("unknown argument: {}", name);
                    }
                }
            }
        }
        Ok(get)
    }
}
