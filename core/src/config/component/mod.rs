mod get;
mod set;

use std::{future::Future, str::FromStr};

use get::GetConfig;
use set::SetConfig;

use crate::{
    cmd_uri::CmdUri,
    component::{AzComponent, AzComponentCtx},
    error::{AzError, AzInternalError},
    pb::{
        self,
        command::{cmd_interface, CmdComponent, CmdHelp, CmdInterface},
        component::{
            execute_response, CheckRequest, CheckResponse, ComponentMetadata, ExecuteRequest,
            ExecuteResponse, InterfaceRequest, InterfaceResponse, MetadataRequest,
            MetadataResponse,
        },
    },
    VERSION,
};

#[derive(Debug, Default)]
pub(crate) struct ConfigComponent {}

// should be generated by component macro later
impl ConfigComponent {
    pub(crate) const URI: &'static str = "cmd://azure/config/";
    pub fn uri() -> CmdUri {
        CmdUri::from_str(Self::URI).unwrap()
    }

    pub fn get_cmd_interface(_: Option<u32>) -> CmdInterface {
        let groups = vec![];
        let commands = vec![
            GetConfig::get_cmd_interface(),
            SetConfig::get_cmd_interface(),
        ];
        CmdInterface {
            name: "config".to_string(),
            help: Some(CmdHelp {
                short: "Manage Azure configuration".to_string(),
                long: None,
            }),
            uri: Self::uri().to_string(),
            level: Some(cmd_interface::Level::Component(CmdComponent {
                version: VERSION.to_string(),
                groups,
                commands,
            })),
        }
    }
}

impl<T: AzComponentCtx> AzComponent<T> for ConfigComponent {
    fn interface<'a>(
        &'a self,
        ctx: &'a T,
        request: InterfaceRequest,
    ) -> std::pin::Pin<Box<dyn Future<Output = Result<InterfaceResponse, AzError>> + Send + 'a>>
    {
        let skip = ConfigComponent::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let depth = match request.depth {
            0 => None, // None means all the depth
            _ => Some(request.depth),
        };

        let segments = cmd_uri.segments().skip(skip).collect::<Vec<_>>().join("/");
        let interface = match segments.as_str() {
            "" => Some(ConfigComponent::get_cmd_interface(depth)),
            "get" => Some(GetConfig::get_cmd_interface()),
            "set" => Some(SetConfig::get_cmd_interface()),
            _ => None, // not found
        };
        Box::pin(async move { Ok(InterfaceResponse { interface }) })
    }

    fn execute<'a>(
        &'a self,
        ctx: &'a T,
        request: ExecuteRequest,
    ) -> std::pin::Pin<Box<dyn Future<Output = Result<ExecuteResponse, AzError>> + Send + 'a>> {
        let skip = ConfigComponent::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let segments = cmd_uri.segments().skip(skip).collect::<Vec<_>>().join("/");
        match segments.as_str() {
            "get" => Box::pin(async move {
                let result = GetConfig::try_from(&request.params)?.run(ctx).await?;
                if let Some(result) = result {
                    Ok(ExecuteResponse {
                        data: Some(execute_response::Data::Json(
                            serde_json::to_vec(&result).unwrap(),
                        )),
                    })
                } else {
                    Ok(ExecuteResponse {
                        data: Some(execute_response::Data::None(pb::component::None {})),
                    })
                }
            }),
            "set" => Box::pin(async move {
                let result = SetConfig::try_from(&request.params)?.run(ctx).await?;
                if let Some(result) = result {
                    Ok(ExecuteResponse {
                        data: Some(execute_response::Data::Json(
                            serde_json::to_vec(&result).unwrap(),
                        )),
                    })
                } else {
                    Ok(ExecuteResponse {
                        data: Some(execute_response::Data::None(pb::component::None {})),
                    })
                }
            }),
            _ => Box::pin(async move {
                Err(AzInternalError::InvalidCmdUriError(request.uri.to_string()).into())
            }),
        }
    }

    fn metadata<'a>(
        &'a self,
        _: &'a T,
        _: MetadataRequest,
    ) -> std::pin::Pin<Box<dyn Future<Output = Result<MetadataResponse, AzError>> + Send + 'a>>
    {
        Box::pin(async move {
            Ok(MetadataResponse {
                metadata: Some(ComponentMetadata {
                    name: "config".to_string(),
                    version: VERSION.to_string(),
                    uri: Self::uri().to_string(),
                    help: Some(CmdHelp {
                        short: "Manage Azure configuration".to_string(),
                        long: None,
                    }),
                }),
            })
        })
    }

    fn check<'a>(
        &'a self,
        _: &'a T,
        request: CheckRequest,
    ) -> std::pin::Pin<Box<dyn Future<Output = Result<CheckResponse, AzError>> + Send + 'a>> {
        let skip = ConfigComponent::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let mut segments = cmd_uri.segments().skip(skip);
        let uri = match segments.next() {
            None => Some(ConfigComponent::uri().with_version(VERSION)),
            Some("get") => Some(
                GetConfig::uri()
                    .with_version(VERSION)
                    .with_param_values("key", segments.collect::<Vec<_>>()),
            ),
            Some("set") => Some(
                SetConfig::uri()
                    .with_version(VERSION)
                    .with_param_values("value", segments.collect::<Vec<_>>()),
            ),
            _ => None,
        };
        Box::pin(async move {
            Ok(CheckResponse {
                uri: uri.map(|u| u.to_string()),
            })
        })
    }
}
