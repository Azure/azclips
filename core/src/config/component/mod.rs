mod cloud;
mod get;
mod set;

use std::str::FromStr;

use async_trait::async_trait;
use cloud::CloudCommandGroup;
use get::GetConfig;
use set::SetConfig;

use crate::{
    cmd_uri::CmdUri,
    component::{
        cmd::{AzCmd, AzCmdGroup},
        AzComponent, AzComponentCtx,
    },
    error::{AzError, AzInternalError},
    pb::{
        command::{cmd_interface, CmdComponent, CmdHelp, CmdInterface, CmdOutputFormat, CmdParams},
        component::{
            execute_response::Data, CheckRequest, CheckResponse, ComponentMetadata, ExecuteRequest,
            ExecuteResponse, InterfaceRequest, InterfaceResponse, MetadataRequest,
            MetadataResponse,
        },
    },
    VERSION,
};

#[derive(Debug, Default)]
pub(crate) struct ConfigComponent {}

// should be generated by component macro later
#[async_trait]
impl AzCmdGroup for ConfigComponent {
    const URI: &'static str = "cmd://azure/config/";
    fn cmd_interface(depth: Option<u32>) -> CmdInterface {
        let mut groups = vec![];
        let mut commands = vec![];
        if depth.is_none() || depth.unwrap() > 0 {
            let depth = depth.map(|d| d - 1);
            groups.push(CloudCommandGroup::cmd_interface(depth));
            commands.push(GetConfig::cmd_interface(depth));
            commands.push(SetConfig::cmd_interface(depth));
        }
        CmdInterface {
            name: "config".to_string(),
            help: Some(CmdHelp {
                short: "Manage Azure configuration".to_string(),
                long: None,
            }),
            uri: Self::uri().to_string(),
            level: Some(cmd_interface::Level::Component(CmdComponent {
                version: VERSION.to_string(),
                groups,
                commands,
            })),
        }
    }

    fn get_interface(
        depth: Option<u32>,
        mut segments: impl Iterator<Item = String>,
    ) -> Option<CmdInterface> {
        match segments.next().as_deref() {
            None => Some(ConfigComponent::cmd_interface(depth)),
            Some("get") => Some(GetConfig::cmd_interface(depth)),
            Some("set") => Some(SetConfig::cmd_interface(depth)),
            Some("cloud") => CloudCommandGroup::get_interface(depth, segments),
            _ => None, // not found
        }
    }

    fn check_uri(mut segments: impl Iterator<Item = String>) -> Option<CmdUri> {
        match segments.next().as_deref() {
            None => Some(ConfigComponent::uri()),
            Some("get") => {
                Some(GetConfig::uri().with_param_values("key", segments.collect::<Vec<_>>()))
            }
            Some("set") => {
                Some(SetConfig::uri().with_param_values("value", segments.collect::<Vec<_>>()))
            }
            Some("cloud") => CloudCommandGroup::check_uri(segments),
            _ => None,
        }
    }

    async fn execute_group<T: AzComponentCtx>(
        ctx: &T,
        mut segments: impl Iterator<Item = String> + Send,
        params: Option<CmdParams>,
        output_format: Option<CmdOutputFormat>,
    ) -> Result<Data, AzError> {
        match segments.next().as_deref() {
            Some("get") => GetConfig::execute(ctx, params, output_format).await,
            Some("set") => SetConfig::execute(ctx, params, output_format).await,
            Some("cloud") => {
                CloudCommandGroup::execute_group(ctx, segments, params, output_format).await
            }
            Some(other) => Err(AzInternalError::InvalidCmdUriError(other.to_string()).into()),
            None => Err(AzInternalError::InvalidCmdUriError(Self::uri().to_string()).into()),
        }
    }
}

#[async_trait]
impl<T: AzComponentCtx> AzComponent<T> for ConfigComponent {
    async fn metadata(&self, _: &T, _: MetadataRequest) -> Result<MetadataResponse, AzError> {
        let interface = Self::cmd_interface(Some(0));
        Ok(MetadataResponse {
            metadata: Some(ComponentMetadata {
                name: interface.name,
                version: VERSION.to_string(),
                uri: interface.uri,
                help: interface.help,
            }),
        })
    }

    async fn interface(
        &self,
        _: &T,
        request: InterfaceRequest,
    ) -> Result<InterfaceResponse, AzError> {
        let skip = Self::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let depth = match request.depth {
            0 => None, // None means all the depth
            _ => Some(request.depth),
        };
        let segments = cmd_uri.segments().skip(skip).map(|s| s.to_string());
        let interface = Self::get_interface(depth, segments);
        Ok(InterfaceResponse { interface })
    }

    async fn execute(&self, ctx: &T, request: ExecuteRequest) -> Result<ExecuteResponse, AzError> {
        let skip = Self::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let segments = cmd_uri.segments().skip(skip).map(|s| s.to_string());
        let result =
            Self::execute_group(ctx, segments, request.params, request.output_format).await?;
        Ok(ExecuteResponse { data: Some(result) })
    }

    async fn check(&self, _: &T, request: CheckRequest) -> Result<CheckResponse, AzError> {
        let skip = Self::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let segments = cmd_uri.segments().skip(skip).map(|s| s.to_string());
        let uri = Self::check_uri(segments).map(|u| {
            // add version and params from the cmd_uri
            let mut uri = u.with_version(VERSION);
            for (key, value) in cmd_uri.params() {
                uri = uri.with_param_values(key, value.collect::<Vec<_>>());
            }
            uri.to_string()
        });
        Ok(CheckResponse { uri })
    }
}
