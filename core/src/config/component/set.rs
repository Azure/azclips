use async_trait::async_trait;
use serde_json::{Map, Value};
use tracing::error;

use crate::{
    component::{AzCommand, AzCommandExecute, AzComponentCtx},
    error::AzError,
    pb::{
        crs_arg, CrsAnyTypeArg, CrsArg, CrsArgHelp, CrsCommand, CrsHelp, CrsObjectArg,
        CrsObjectArgAdditionalProperties, CrsParams,
    },
    AzCore, VERSION,
};

#[derive(Debug, Default)]
pub struct SetConfig {
    // the value will be any type
    value: Map<String, Value>,

    // internal property which will not exposed
    _patch_keys: Vec<String>,
}

#[async_trait]
impl AzCommandExecute for SetConfig {
    type Output = Value;

    async fn run<T: AzComponentCtx>(&self, _: &T) -> Result<Option<Self::Output>, AzError> {
        let core = AzCore::instance().await;
        let mut cfg = core.cfg.write().await;
        // TODO apply patch keys, currently patch will applied
        for (k, v) in self.value.iter() {
            cfg.settings.insert(k.to_string(), v.clone());
        }
        cfg.save()?;
        Ok(Some(Value::Object(cfg.settings.clone())))
    }
}

// TODO move it to "crs://azure/config/settings/set"
// will be generated by command macro later
impl AzCommand for SetConfig {
    const URI: &'static str = "crs://azure/config/set";

    fn build_interface(_: Option<u32>) -> CrsCommand {
        CrsCommand {
            name: "set".to_string(),
            uri: Self::uri().to_string(),
            version: VERSION.to_string(),
            help: Some(CrsHelp {
                short: "Set a configuration value".to_string(),
                long: None,
            }),
            args: Self::args(),
            positional_args: vec!["value".to_string()],
        }
    }

    fn args() -> Vec<CrsArg> {
        vec![CrsArg {
            var_name: "value".to_string(),
            name: "value".to_string(),
            options: vec!["value".to_string()],
            required: true,
            nullable: true,
            help: Some(CrsArgHelp {
                short: "The configuration to set, support partial update with `<key>=<value>`, if directly apply from a json file, please use `file://<path>` as the value".to_string(),
                ..Default::default()
            }),
            arg_type: Some(crs_arg::ArgType::Object(Box::new(CrsObjectArg {
                additional_props: Some(Box::new(CrsObjectArgAdditionalProperties {
                    item: Some(Box::new( CrsArg {
                        var_name: "value{}".to_string(),
                        nullable: true,
                        arg_type: Some(crs_arg::ArgType::AnyType(CrsAnyTypeArg::default())),
                        ..Default::default()
                    })),
                })),
                ..Default::default()
            }))),
            ..Default::default()
        }]
    }

    fn try_from(params: Option<CrsParams>) -> Result<Self, AzError> {
        let mut set = Self::default();
        if let Some(params) = params {
            for (name, v) in params.params.iter() {
                match name.as_str() {
                    "value" => set.value = serde_json::from_slice(v).expect("failed to parse json"),
                    _ => {
                        error!("unknown argument: {}", name);
                    }
                }
            }
            set._patch_keys = params.patch_keys.to_owned();
        }
        Ok(set)
    }
}
