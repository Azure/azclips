use add::AddPlugin;
use async_trait::async_trait;
use demo::DemoCommandGroup;
use list::ListPlugins;
use remove::RemovePlugin;
use show::ShowPlugin;
use upgrade::UpgradePlugin;

use crate::{
    component::{AzCommand, AzCommandGroup, AzComponentCtx, AzComponentImpl},
    error::{AzError, AzInternalError},
    pb::{execute_response, CrsCommandGroup, CrsHelp, CrsInterface, CrsOutputFormat, CrsParams},
    uri::CrsUri,
};

/// The built-in component for managing the plugins
#[derive(Debug, Default)]
pub struct PluginComponent {}

// should be generated by component macro later
#[async_trait]
impl AzCommandGroup for PluginComponent {
    const URI: &'static str = "crs://azure/plugin/";

    fn build_interface(depth: Option<u32>) -> CrsCommandGroup {
        let mut groups = vec![];
        let mut commands = vec![];
        if depth.is_none_or(|d| d > 0) {
            let depth = depth.map(|d| d - 1);
            commands.push(AddPlugin::build_interface(depth));
            commands.push(ListPlugins::build_interface(depth));
            commands.push(RemovePlugin::build_interface(depth));
            commands.push(ShowPlugin::build_interface(depth));
            commands.push(UpgradePlugin::build_interface(depth));

            groups.push(DemoCommandGroup::build_interface(depth));
        }
        CrsCommandGroup {
            name: "plugin".to_string(),
            uri: Self::uri().to_string(),
            help: Some(CrsHelp {
                short: "Manage Azure plugins.".to_string(),
                long: None,
            }),
            groups,
            commands,
        }
    }

    fn find_interface(
        depth: Option<u32>,
        mut segments: impl Iterator<Item = String>,
    ) -> Option<CrsInterface> {
        match segments.next().as_deref() {
            None => Some(Self::build_interface(depth).into()),
            Some("demo") => Some(DemoCommandGroup::build_interface(depth).into()),
            Some("add") => Some(AddPlugin::build_interface(depth).into()),
            Some("list") => Some(ListPlugins::build_interface(depth).into()),
            Some("remove") => Some(RemovePlugin::build_interface(depth).into()),
            Some("show") => Some(ShowPlugin::build_interface(depth).into()),
            Some("upgrade") => Some(UpgradePlugin::build_interface(depth).into()),
            _ => None,
        }
    }

    fn resolve_uri(mut segments: impl Iterator<Item = String>) -> Option<CrsUri> {
        match segments.next().as_deref() {
            None => Some(Self::uri()),
            Some("demo") => Some(DemoCommandGroup::uri()),
            Some("add") => Some(AddPlugin::uri()),
            Some("list") => Some(ListPlugins::uri()),
            Some("remove") => Some(RemovePlugin::uri()),
            Some("show") => Some(ShowPlugin::uri()),
            Some("upgrade") => Some(UpgradePlugin::uri()),
            _ => None,
        }
    }

    async fn execute_group<T: AzComponentCtx>(
        ctx: &T,
        mut segments: impl Iterator<Item = String> + Send,
        params: Option<CrsParams>,
        output_format: Option<CrsOutputFormat>,
    ) -> Result<execute_response::Data, AzError> {
        match segments.next().as_deref() {
            Some("demo") => {
                DemoCommandGroup::execute_group(ctx, segments, params, output_format).await
            }
            Some("add") => AddPlugin::execute(ctx, params, output_format).await,
            Some("list") => ListPlugins::execute(ctx, params, output_format).await,
            Some("remove") => RemovePlugin::execute(ctx, params, output_format).await,
            Some("show") => ShowPlugin::execute(ctx, params, output_format).await,
            Some("upgrade") => UpgradePlugin::execute(ctx, params, output_format).await,
            _ => Err(AzInternalError::InvalidCrsUriError(Self::uri().to_string()).into()),
        }
    }
}

impl<T: AzComponentCtx> AzComponentImpl<T> for PluginComponent {
    const VERSION: &'static str = crate::VERSION;
}
