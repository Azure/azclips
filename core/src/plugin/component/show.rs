use async_trait::async_trait;
use serde_json::Value;
use tracing::error;

use crate::{
    component::{AzCommand, AzCommandExecute, AzComponentCtx},
    config::cloud::AzCloud,
    error::AzError,
    pb::{
        crs_arg, crs_string_arg, CrsArg, CrsArgHelp, CrsCommand, CrsHelp, CrsParams, CrsStringArg,
        CrsStringFormat,
    },
    VERSION,
};

#[derive(Debug, Default)]
pub struct ShowPlugin {
    name: String,
    cloud: Option<AzCloud>,
}

#[async_trait]
impl AzCommandExecute for ShowPlugin {
    type Output = Value;

    async fn run<T: AzComponentCtx>(&self, _: &T) -> Result<Option<Self::Output>, AzError> {
        println!("show plugin: {:?}", self);

        Ok(None)
    }
}

// will be generated by command macro later
impl AzCommand for ShowPlugin {
    const URI: &'static str = "crs://azure/plugin/show";

    fn build_interface(_: Option<u32>) -> CrsCommand {
        CrsCommand {
            name: "show".to_string(),
            uri: Self::uri().to_string(),
            version: VERSION.to_string(),
            help: Some(CrsHelp {
                short: "Show a installed plugin details".to_string(),
                long: Some("Show a installed plugin details".to_string()),
            }),
            args: Self::args(),
            positional_args: vec![],
        }
    }

    fn args() -> Vec<CrsArg> {
        vec![
            CrsArg {
                var_name: "name".to_string(),
                name: "name".to_string(),
                options: vec![
                    "name".to_string(),
                    "n".to_string(),
                ],
                help: Some(CrsArgHelp {
                    short: "The name of the plugin to show".to_string(),
                    ..Default::default()
                }),
                required: true,
                arg_type: Some(crs_arg::ArgType::String(CrsStringArg {
                    format: Some(crs_string_arg::Format::String(CrsStringFormat::default())),
                    ..Default::default()
                })),
                ..Default::default()
            },
            CrsArg {
                var_name: "cloud".to_string(),
                name: "cloud".to_string(),
                options: vec![
                    "cloud".to_string(),
                ],
                help: Some(CrsArgHelp {
                    short: "The cloud environment to show the plugin details, if not specified, the current active cloud will be used".to_string(),
                    ..Default::default()
                }),
                arg_type: Some(crs_arg::ArgType::String(CrsStringArg {
                    format: Some(crs_string_arg::Format::String(CrsStringFormat::default())),
                    ..Default::default()
                })),
                ..Default::default()
            }
        ]
    }

    fn try_from(params: Option<CrsParams>) -> Result<Self, AzError> {
        let mut show = Self::default();
        if let Some(params) = params {
            for (name, v) in params.params.iter() {
                match name.as_str() {
                    "name" => {
                        show.name = serde_json::from_slice(v).expect("failed to parse json");
                    }
                    "cloud" => {
                        show.cloud = serde_json::from_slice(v).expect("failed to parse json");
                    }
                    _ => {
                        error!("unknown argument: {}", name);
                    }
                }
            }
        }
        Ok(show)
    }
}
