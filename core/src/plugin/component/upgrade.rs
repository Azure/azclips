use async_trait::async_trait;
use serde_json::{json, Value};
use tracing::error;

use crate::{
    component::{AzCommand, AzCommandExecute, AzComponentCtx},
    config::cloud::AzCloud,
    error::AzError,
    pb::{
        crs_arg, crs_string_arg, CrsArg, CrsArgDefault, CrsArgHelp, CrsCommand, CrsHelp, CrsParams,
        CrsStringArg, CrsStringFormat,
    },
    VERSION,
};

#[derive(Debug, Default)]
pub struct UpgradePlugin {
    name: String,
    version: String,
    cloud: Option<AzCloud>,
}

#[async_trait]
impl AzCommandExecute for UpgradePlugin {
    type Output = Value;

    async fn run<T: AzComponentCtx>(&self, _: &T) -> Result<Option<Self::Output>, AzError> {
        println!("upgrade plugin: {:?}", self);
        Ok(None)
    }
}

// will be generated by command macro later
impl AzCommand for UpgradePlugin {
    const URI: &'static str = "crs://azure/plugin/upgrade";

    fn build_interface(_: Option<u32>) -> CrsCommand {
        CrsCommand {
            name: "upgrade".to_string(),
            uri: Self::uri().to_string(),
            version: VERSION.to_string(),
            help: Some(CrsHelp {
                short: "Upgrade a plugin".to_string(),
                long: Some(
                    "Upgrade a plugin to a specific version in the cloud environment".to_string(),
                ),
            }),
            args: Self::args(),
            positional_args: vec![],
        }
    }

    fn args() -> Vec<CrsArg> {
        vec![
            CrsArg {
                var_name: "name".to_string(),
                name: "name".to_string(),
                options: vec![
                    "name".to_string(),
                    "n".to_string(),
                ],
                help: Some(CrsArgHelp {
                    short: "The name of the plugin".to_string(),
                    ..Default::default()
                }),
                required: true,
                arg_type: Some(crs_arg::ArgType::String(CrsStringArg {
                    format: Some(crs_string_arg::Format::String(CrsStringFormat::default())),
                    ..Default::default()
                })),
                ..Default::default()
            },
            CrsArg {
                var_name: "version".to_string(),
                name: "version".to_string(),
                options: vec![
                    "version".to_string(),
                    "version-tag".to_string(),
                    "v".to_string(),
                ],
                help: Some(CrsArgHelp {
                    short: "The version or version tag of the plugin".to_string(),
                    ..Default::default()
                }),
                required: true,
                default: Some(CrsArgDefault {
                    value: json!("latest").to_string(),
                    ..Default::default()
                }),
                arg_type: Some(crs_arg::ArgType::String(CrsStringArg {
                    format: Some(crs_string_arg::Format::String(CrsStringFormat::default())),
                    ..Default::default()
                })),
                ..Default::default()
            },
            CrsArg {
                var_name: "cloud".to_string(),
                name: "cloud".to_string(),
                options: vec![
                    "cloud".to_string(),
                ],
                help: Some(CrsArgHelp {
                    short: "The cloud environment the plugin will be added to, if not specified, the current active cloud will be used".to_string(),
                    ..Default::default()
                }),
                arg_type: Some(crs_arg::ArgType::String(CrsStringArg {
                    format: Some(crs_string_arg::Format::String(CrsStringFormat::default())),
                    ..Default::default()
                })),
                ..Default::default()
            }
        ]
    }

    fn try_from(params: Option<CrsParams>) -> Result<Self, AzError> {
        let mut upgrade = Self::default();
        if let Some(params) = params {
            for (name, v) in params.params.iter() {
                match name.as_str() {
                    "name" => {
                        upgrade.name = serde_json::from_slice(v).expect("failed to parse json");
                    }
                    "version" => {
                        upgrade.version = serde_json::from_slice(v).expect("failed to parse json");
                    }
                    "cloud" => {
                        upgrade.cloud = serde_json::from_slice(v).expect("failed to parse json");
                    }
                    _ => {
                        error!("unknown argument: {}", name);
                    }
                }
            }
        }
        Ok(upgrade)
    }
}
