mod login;
mod logout;

use login::Login;
use logout::Logout;
use std::str::FromStr;

use crate::{
    cmd_uri::CmdUri,
    component::{AzComponent, AzComponentCtx},
    error::{AzError, AzInternalError},
    pb::{
        self,
        command::{cmd_interface, CmdComponent, CmdHelp, CmdInterface},
        component::{
            execute_response, CheckRequest, CheckResponse, ComponentMetadata, ExecuteRequest,
            ExecuteResponse, InterfaceRequest, InterfaceResponse, MetadataRequest,
            MetadataResponse,
        },
    },
    VERSION,
};

#[derive(Debug, Default)]
pub(crate) struct TopComponent {}

// will be generated by component macro later
impl TopComponent {
    pub(crate) const URI: &'static str = "cmd://azure/";

    pub fn uri() -> CmdUri {
        CmdUri::from_str(Self::URI).unwrap()
    }

    pub fn get_cmd_interface(_: Option<u32>) -> CmdInterface {
        let groups = vec![];
        let commands = vec![Login::get_cmd_interface(), Logout::get_cmd_interface()];
        CmdInterface {
            name: "".to_string(),
            help: Some(CmdHelp {
                short: "Contain the top level commands".to_string(),
                long: None,
            }),
            uri: Self::URI.to_string(),
            level: Some(cmd_interface::Level::Component(CmdComponent {
                version: "1.0.0".to_string(),
                groups,
                commands,
            })),
        }
    }
}

const COMPONENT_LONG_SUMMARY: &str = r"
     /\
    /  \    _____   _ _  ___ _
   / /\ \  |_  / | | | \'__/ _\
  / ____ \  / /| |_| | | |  __/
 /_/    \_\/___|\__,_|_|  \___|

 Welcome to the cool new Azure CLIENT TOOL!
";

// should be generated by component macro later
impl<T: AzComponentCtx> AzComponent<T> for TopComponent {
    fn interface<'a>(
        &'a self,
        _: &'a T,
        request: InterfaceRequest,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = Result<InterfaceResponse, AzError>> + Send + 'a>,
    > {
        let skip = TopComponent::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let depth = match request.depth {
            0 => None, // None means all the depth
            _ => Some(request.depth),
        };

        let segments = cmd_uri.segments().skip(skip).collect::<Vec<_>>().join("/");
        let interface = match segments.as_str() {
            "" => Some(TopComponent::get_cmd_interface(depth)),
            "login" => Some(Login::get_cmd_interface()),
            "logout" => Some(Logout::get_cmd_interface()),
            _ => None,
        };

        Box::pin(async move { Ok(InterfaceResponse { interface }) })
    }

    fn execute<'a>(
        &'a self,
        ctx: &'a T,
        request: ExecuteRequest,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = Result<ExecuteResponse, AzError>> + Send + 'a>,
    > {
        let skip = TopComponent::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        if !cmd_uri.executable() {
            return Box::pin(async move {
                Err(AzInternalError::InvalidCmdUriError(request.uri.to_string()).into())
            });
        }
        let segments = cmd_uri.segments().skip(skip).collect::<Vec<_>>().join("/");
        match segments.as_str() {
            "login" => Box::pin(async move {
                let result = Login::try_from(&request.params)?.run(ctx).await?;
                Ok(ExecuteResponse {
                    data: Some(execute_response::Data::None(pb::component::None {})),
                })
            }),
            "logout" => Box::pin(async move {
                let result = Logout::try_from(&request.params)?.run(ctx).await?;
                Ok(ExecuteResponse {
                    data: Some(execute_response::Data::None(pb::component::None {})),
                })
            }),
            _ => Box::pin(async move {
                Err(AzInternalError::InvalidCmdUriError(request.uri.to_string()).into())
            }),
        }
    }

    fn metadata<'a>(
        &'a self,
        _: &'a T,
        _: MetadataRequest,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = Result<MetadataResponse, AzError>> + Send + 'a>,
    > {
        Box::pin(async move {
            Ok(MetadataResponse {
                metadata: Some(ComponentMetadata {
                    name: "azure".to_string(),
                    version: VERSION.to_string(),
                    uri: Self::uri().to_string(),
                    help: Some(CmdHelp {
                        short: "".to_string(),
                        long: Some(COMPONENT_LONG_SUMMARY.to_string()),
                    }),
                }),
            })
        })
    }

    fn check<'a>(
        &'a self,
        _: &'a T,
        request: CheckRequest,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = Result<CheckResponse, AzError>> + Send + 'a>,
    > {
        let skip = TopComponent::uri().segments().count();
        let cmd_uri = CmdUri::from_str(&request.uri).unwrap();
        let segments = cmd_uri.segments().skip(skip).collect::<Vec<_>>().join("/");
        let uri = match segments.as_str() {
            "" => Some(TopComponent::uri().with_version(VERSION)),
            "login" => Some(Login::uri().with_version(VERSION)),
            "logout" => Some(Logout::uri().with_version(VERSION)),
            _ => None,
        };
        Box::pin(async move {
            Ok(CheckResponse {
                uri: uri.map(|u| u.to_string()),
            })
        })
    }
}
