    public static IReadOnlyCollection<string> Names => s_cats.Keys;

    public static bool TryGet(string name, out string art)
    {
        if (s_cats.TryGetValue(name, out var value))
        {
            art = value;
            return true;
        }

        art = string.Empty;
        return false;
    }

    /// <summary>Picks a cat by name for testing, or a random one when <paramref name="rng"/> is used.</summary>
    public static string Random(Random rng)
    {
        var names = s_cats.Keys.ToArray();
        return s_cats[names[rng.Next(names.Length)]];
    }
