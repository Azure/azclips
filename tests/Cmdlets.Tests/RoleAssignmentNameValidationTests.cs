using System.Management.Automation;
using Microsoft.Azure.Azclips.Cmdlets.Resources;

namespace Cmdlets.Tests;

/// <summary>
/// Tests for <see cref="ValidateRoleAssignmentNameAttribute"/>, which validates
/// <c>Remove-AzRoleAssignment -Name</c> at parameter-binding time. This closes a review comment: the
/// cmdlet calls <c>ShouldProcess</c> before the orchestrator validates the name, so without a
/// bind-time check <c>Remove-AzRoleAssignment -Name not-a-guid -WhatIf</c> would report a successful
/// what-if for an operation a real run is guaranteed to reject. Binding-time validation runs before
/// <c>ShouldProcess</c>, so <c>-WhatIf</c> now fails consistently with a real run.
/// </summary>
public class RoleAssignmentNameValidationTests
{
    [Theory]
    [InlineData("aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee")]
    [InlineData("  aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee  ")] // trimmed, matching the orchestrator
    [InlineData("AAAAAAAA-BBBB-CCCC-DDDD-EEEEEEEEEEEE")]     // case-insensitive
    [InlineData("{aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee}")]   // Guid.TryParse accepts braces
    public void IsValid_AcceptsGuidForms(string name)
    {
        Assert.True(ValidateRoleAssignmentNameAttribute.IsValid(name));
    }

    [Theory]
    [InlineData("not-a-guid")]
    [InlineData("")]
    [InlineData("   ")]
    public void IsValid_RejectsNonGuid(string name)
    {
        Assert.False(ValidateRoleAssignmentNameAttribute.IsValid(name));
    }

    [Fact]
    public void IsValid_RejectsNonString()
    {
        Assert.False(ValidateRoleAssignmentNameAttribute.IsValid(null));
        Assert.False(ValidateRoleAssignmentNameAttribute.IsValid(42));
    }

    // AllowEmpty = true models the create surface, where -Name is optional and a blank value is
    // auto-generated by the orchestrator rather than rejected.
    [Theory]
    [InlineData("")]
    [InlineData("   ")]
    [InlineData(null)]
    public void IsValid_AllowEmpty_AcceptsBlank(string? name)
    {
        Assert.True(ValidateRoleAssignmentNameAttribute.IsValid(name, allowEmpty: true));
    }

    [Fact]
    public void IsValid_AllowEmpty_StillRejectsNonBlankNonGuid()
    {
        Assert.False(ValidateRoleAssignmentNameAttribute.IsValid("not-a-guid", allowEmpty: true));
        Assert.True(ValidateRoleAssignmentNameAttribute.IsValid("aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", allowEmpty: true));
    }

    [Fact]
    public void Validate_ThrowsForNonGuid_SoWhatIfCannotReportAnImpossibleDelete()
    {
        var attribute = new ValidateRoleAssignmentNameAttribute();
        // ValidateArgumentsAttribute.Validate is protected; the engine invokes it during binding.
        var validate = typeof(ValidateRoleAssignmentNameAttribute).GetMethod(
            "Validate", System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic)!;

        var ex = Assert.Throws<System.Reflection.TargetInvocationException>(
            () => validate.Invoke(attribute, new object?[] { "not-a-guid", null }));
        var inner = Assert.IsType<ValidationMetadataException>(ex.InnerException);
        Assert.Contains("must be a GUID", inner.Message);
    }

    [Fact]
    public void Validate_PassesForGuid()
    {
        var attribute = new ValidateRoleAssignmentNameAttribute();
        var validate = typeof(ValidateRoleAssignmentNameAttribute).GetMethod(
            "Validate", System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic)!;

        // No exception = valid.
        validate.Invoke(attribute, new object?[] { "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", null });
    }
}
