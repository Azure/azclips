using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Ace.Generator;

/// <summary>
/// Roslyn helpers for emitting scaffold C# files. The real generators replace the
/// stub bodies with actual member emission; this exists so the scaffold shows the
/// intended file/namespace/type shape.
/// </summary>
internal static class CSharpStub
{
    private const string Banner = "// <auto-generated /> Scaffold stub — replace with real emission.";

    /// <summary>
    /// Render a single-class compilation unit:
    /// <c>namespace ns; public [abstract] partial class name [: baseType] { }</c>.
    /// </summary>
    public static string Class(string @namespace, string name, string? baseType = null, bool isAbstract = false)
    {
        ClassDeclarationSyntax cls = ClassDeclaration(name).AddModifiers(Token(SyntaxKind.PublicKeyword));
        if (isAbstract)
        {
            cls = cls.AddModifiers(Token(SyntaxKind.AbstractKeyword));
        }

        cls = cls.AddModifiers(Token(SyntaxKind.PartialKeyword));
        if (baseType is not null)
        {
            cls = cls.WithBaseList(BaseList(SingletonSeparatedList<BaseTypeSyntax>(SimpleBaseType(ParseTypeName(baseType)))));
        }

        CompilationUnitSyntax unit = CompilationUnit()
            .AddMembers(FileScopedNamespaceDeclaration(ParseName(@namespace)).AddMembers(cls))
            .NormalizeWhitespace();

        return Banner + Environment.NewLine + unit.ToFullString() + Environment.NewLine;
    }
}
