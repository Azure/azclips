using System.Text;
using Ace.Generator.Model;
using Ace.Generator.Model.Ir;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Ace.Generator.Generators;

/// <summary>
/// Emits the extension's <c>ExtensionIndex</c> — the command table the engine dispatches through —
/// from the PowerShell surface on <see cref="IRDocument.Ps"/>.
/// </summary>
/// <remarks>
/// One <c>CommandMetadata</c> per <em>parameter set</em>, not per command. A
/// <c>PSCommandAttribute</c> holds every variant of a cmdlet at once, but the engine dispatches to
/// one processor per invocation, so each set becomes its own table entry bound to the processor for
/// its source operation. Entries are suffixed <c>Verb-Noun_Set</c> only when the cmdlet has more
/// than one set, matching the hand-written indexes (<c>Get-AzVM_Get</c> / <c>Get-AzVM_List</c>, but
/// a bare <c>New-AzVM</c>).
/// <para>
/// The CLI table is emitted empty: that surface arrives with <c>IR.cli</c>, and an empty table is
/// truthful about a PowerShell-only extension where throwing would not be.
/// </para>
/// </remarks>
internal sealed class ExtensionIndexGenerator : IArtifactGenerator
{
    private const string Banner = "// <auto-generated /> Emitted from IR by Ace.Generator.";

    public string Name => "extension-index";

    public IEnumerable<GeneratedFile> Produce(GenerationContext context)
    {
        PS? ps = context.Ir.Ps;
        if (ps is null || ps.Commands.Count == 0)
        {
            yield break;
        }

        var operations = new Dictionary<string, IROperation>(StringComparer.Ordinal);
        foreach (IROperation operation in context.Ir.Operations)
        {
            if (operation.Id is not null)
            {
                operations[IrIds.Serialize(operation.Id)] = operation;
            }
        }

        var entries = new List<Entry>();
        foreach (PSCommandAttribute command in ps.Commands)
        {
            if (command.Hidden == true)
            {
                continue;
            }

            foreach (PSParameterSetAttribute set in command.ParameterSets)
            {
                if (!operations.TryGetValue(IrIds.Serialize(set.SourceOperationId), out IROperation? operation))
                {
                    context.Report(
                        Model.DiagnosticSeverity.Warning,
                        "ace-generator/unresolved-source-operation",
                        $"Parameter set '{set.Name}' of '{command.Verb}-{command.Noun}' names source operation "
                            + $"'{set.SourceOperationId.Name}', which is not in the document; the set was skipped.");
                    continue;
                }

                entries.Add(
                    new Entry(
                        InvocationName: command.ParameterSets.Count > 1
                            ? $"{command.Verb}-{command.Noun}_{set.Name}"
                            : $"{command.Verb}-{command.Noun}",
                        ProcessorType: ProcessorNaming.TypeName(operation),
                        Aliases: command.Alias ?? [],
                        Parameters: ParametersFor(command, set.Name, TypeIndex(context.Ir), EnumIndex(context.Ir))));
            }
        }

        if (entries.Count == 0)
        {
            yield break;
        }

        // The core carries the interface and the lookups; each client surface contributes its
        // commands through its own partial, so the surfaces can be generated independently.
        // Only the core claims the class name: both files declare the same partial type, and the
        // orchestrator's class map holds one path per type.
        foreach ((string path, string source, string? className) in new[]
        {
            ("ExtensionIndex.cs", EmitCore(context.Options), "ExtensionIndex"),
            ("ExtensionIndex.Ps.cs", EmitPowerShell(context.Options, entries), (string?)null),
        })
        {
            // A malformed table should fail here, naming this generator, rather than in the
            // consumer's build where the cause is a generated file nobody wrote.
            foreach (Diagnostic diagnostic in SyntaxFactory.ParseCompilationUnit(source).GetDiagnostics())
            {
                if (diagnostic.Severity == Microsoft.CodeAnalysis.DiagnosticSeverity.Error)
                {
                    context.Report(
                        Model.DiagnosticSeverity.Error,
                        "ace-generator/invalid-extension-index",
                        $"Emitted an unparseable extension index ({path}): {diagnostic.GetMessage()}");
                }
            }

            yield return new GeneratedFile(path, source, className);
        }
    }

    /// <summary>Every id a PS parameter can name, mapped to the IR type it binds.</summary>
    private static Dictionary<string, IRTypeRef> TypeIndex(IRDocument ir)
    {
        var index = new Dictionary<string, IRTypeRef>(StringComparer.Ordinal);

        foreach (IROperation operation in ir.Operations)
        {
            foreach (IRParameter parameter in operation.PathParameters
                .Concat(operation.QueryParameters)
                .Concat(operation.HeaderParameters))
            {
                if (parameter.Id is not null && parameter.Type is not null)
                {
                    index[IrIds.Serialize(parameter.Id)] = parameter.Type;
                }
            }
        }

        foreach (IRModel model in ir.Models)
        {
            foreach (IRProperty property in model.Properties)
            {
                if (property.Id is not null && TypeRefOf(property) is { } type)
                {
                    index[IrIds.Serialize(property.Id)] = type;
                }
            }
        }

        return index;
    }

    /// <summary>Enum members by enum id, for the <c>AllowedValues</c> of a parameter that names one.</summary>
    private static Dictionary<string, string[]> EnumIndex(IRDocument ir)
    {
        var index = new Dictionary<string, string[]>(StringComparer.Ordinal);
        foreach (IREnum @enum in ir.Enums)
        {
            if (@enum.Id is not null)
            {
                index[IrIds.Serialize(@enum.Id)] = [.. @enum.Members.Select(m => m.Value?.ToString() ?? m.Name)];
            }
        }
        return index;
    }

    private static IRTypeRef? TypeRefOf(IRProperty property) => property switch
    {
        IRPropertyPrimitive p => p.Type,
        IRPropertyObject p => p.Type,
        IRPropertyCollection p => p.Type,
        IRPropertyEnum p => p.Type,
        IRPropertyUnion p => p.Type,
        _ => null,
    };

    /// <summary>
    /// The C# type a parameter binds as. Enums render as <c>string</c> with their members carried
    /// on <c>AllowedValues</c> — the shape the hand-written indexes use, and the only one that
    /// compiles while the model stage does not emit enum types.
    /// </summary>
    private static string Render(IRTypeRef type) => type switch
    {
        IRTypeRefEnum => "string",
        IRTypeRefArray a => $"IList<{Render(a.Element)}>",
        IRTypeRefDictionary d => $"IDictionary<string, {Render(d.Value)}>",
        _ => IrTypeMapper.ToCSharp(type),
    };

    /// <summary>The parameters that take part in <paramref name="setName"/>, with per-set overrides applied.</summary>
    private static IReadOnlyList<Parameter> ParametersFor(
        PSCommandAttribute command,
        string setName,
        IReadOnlyDictionary<string, IRTypeRef> types,
        IReadOnlyDictionary<string, string[]> enums)
    {
        var parameters = new List<Parameter>();

        foreach (PSParameterAttribute parameter in command.Parameters)
        {
            PSParameterSetOverride? over = null;
            if (parameter.ParameterSets is { } map)
            {
                if (!map.TryGetValue(setName, out over))
                {
                    continue;
                }
            }
            else if (parameter.ParameterSetName is { } only && only != setName)
            {
                continue;
            }

            // An identity parameter binds the module identity type, which nothing emits yet.
            IRTypeRef? type = parameter.Identity == true || parameter.SourceParameterId is null
                ? null
                : types.TryGetValue(IrIds.Serialize(parameter.SourceParameterId), out IRTypeRef? found)
                    ? found
                    : null;

            string[] allowed = type is IRTypeRefEnum e
                && e.Id is not null
                && enums.TryGetValue(IrIds.Serialize(e.Id), out string[]? members)
                    ? members
                    : [];

            parameters.Add(
                new Parameter(
                    Name: parameter.Name,
                    Type: type is null ? "object" : Render(type),
                    Help: over?.HelpMessage ?? parameter.HelpMessage ?? string.Empty,
                    Required: over?.Mandatory ?? parameter.Mandatory ?? false,
                    Aliases: parameter.Alias ?? [],
                    AllowedValues: allowed));
        }

        return parameters;
    }

    /// <summary>
    /// The surface-agnostic half: the interface, the tables, and the lookups. Each surface fills
    /// its table through a partial hook. A hook with no implementing partial compiles away, so a
    /// module that generates only one surface still builds and simply reports an empty table for
    /// the other.
    /// </summary>
    private static string EmitCore(GeneratorOptions options)
    {
        string ns = options.RootNamespace;
        var source = new StringBuilder();

        source.AppendLine(Banner);
        source.AppendLine("using Core.Abstractions;");
        source.AppendLine();
        source.AppendLine($"namespace {ns};");
        source.AppendLine();
        source.AppendLine("public partial class ExtensionIndex : IExtensionIndex");
        source.AppendLine("{");
        source.AppendLine("    private static readonly Dictionary<string, CommandMetadata> s_psTable = BuildPowerShell();");
        source.AppendLine("    private static readonly Dictionary<string, CommandMetadata> s_cliTable = BuildCli();");
        source.AppendLine();
        source.AppendLine("    static partial void AddPowerShellCommands(Dictionary<string, CommandMetadata> table);");
        source.AppendLine();
        source.AppendLine("    static partial void AddCliCommands(Dictionary<string, CommandMetadata> table);");
        source.AppendLine();
        source.AppendLine("    private static Dictionary<string, CommandMetadata> BuildPowerShell()");
        source.AppendLine("    {");
        source.AppendLine("        var table = new Dictionary<string, CommandMetadata>(StringComparer.OrdinalIgnoreCase);");
        source.AppendLine("        AddPowerShellCommands(table);");
        source.AppendLine("        return table;");
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine("    private static Dictionary<string, CommandMetadata> BuildCli()");
        source.AppendLine("    {");
        source.AppendLine("        var table = new Dictionary<string, CommandMetadata>(StringComparer.Ordinal);");
        source.AppendLine("        AddCliCommands(table);");
        source.AppendLine("        return table;");
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine("    public CommandMetadata GetCommandMetadata(string name, ClientType clientType) =>");
        source.AppendLine("        GetCommandTable(clientType).TryGetValue(name, out CommandMetadata? metadata)");
        source.AppendLine("            ? metadata");
        source.AppendLine("            : throw new KeyNotFoundException($\"Command '{name}' not found for client type '{clientType}'.\");");
        source.AppendLine();
        source.AppendLine("    public IReadOnlyDictionary<string, CommandMetadata> GetCommandTable(ClientType clientType) => clientType switch");
        source.AppendLine("    {");
        source.AppendLine("        ClientType.PowerShell => s_psTable,");
        source.AppendLine("        ClientType.CLI => s_cliTable,");
        source.AppendLine("        _ => throw new ArgumentException($\"Client type '{clientType}' is not supported.\"),");
        source.AppendLine("    };");
        source.AppendLine();
        source.AppendLine("    public IEnumerable<CommandMetadata> GetAllCommands(ClientType clientType) => GetCommandTable(clientType).Values;");
        source.AppendLine();
        source.AppendLine("    public IEnumerable<string> GetCommandKeys(ClientType clientType) => GetCommandTable(clientType).Keys;");
        source.AppendLine("}");

        return source.ToString();
    }

    private static string EmitPowerShell(GeneratorOptions options, IReadOnlyList<Entry> entries)
    {
        string ns = options.RootNamespace;
        var source = new StringBuilder();

        source.AppendLine(Banner);
        source.AppendLine("using Core.Abstractions;");
        // Parameters can bind model types, which the model stage emits into a child namespace.
        source.AppendLine($"using {ns}.Models;");
        source.AppendLine();
        source.AppendLine($"namespace {ns};");
        source.AppendLine();
        source.AppendLine("public partial class ExtensionIndex");
        source.AppendLine("{");
        source.AppendLine("    static partial void AddPowerShellCommands(Dictionary<string, CommandMetadata> table)");
        source.AppendLine("    {");

        foreach (Entry entry in entries)
        {
            source.AppendLine($"        table[{Literal(entry.InvocationName)}] = new(");
            source.AppendLine($"            Name: {Literal(entry.ProcessorType)},");
            source.AppendLine($"            InvocationName: {Literal(entry.InvocationName)},");
            source.AppendLine($"            Aliases: [{string.Join(", ", entry.Aliases.Select(Literal))}],");
            source.AppendLine($"            FullName: {Literal($"{ns}.Processors.{entry.ProcessorType}")},");
            source.AppendLine($"            AssemblyName: {Literal(ns)},");
            source.AppendLine($"            ProcessorType: typeof(Processors.{entry.ProcessorType}),");
            source.AppendLine("            Parameters: new Dictionary<string, ParameterMetadata>");
            source.AppendLine("            {");
            foreach (Parameter parameter in entry.Parameters)
            {
                source.AppendLine(
                    $"                [{Literal(parameter.Name)}] = new({Literal(parameter.Name)}, {Literal(parameter.Name)}, "
                        + $"typeof({parameter.Type}), {Literal(parameter.Help)}, "
                        + $"IsRequired: {(parameter.Required ? "true" : "false")}, "
                        + $"Aliases: [{string.Join(", ", parameter.Aliases.Select(Literal))}], "
                        + $"AllowedValues: [{string.Join(", ", parameter.AllowedValues.Select(Literal))}]),");
            }
            source.AppendLine("            },");
            source.AppendLine("            ParameterAliases: new Dictionary<string, string>");
            source.AppendLine("            {");
            foreach (Parameter parameter in entry.Parameters)
            {
                foreach (string alias in parameter.Aliases)
                {
                    source.AppendLine($"                [{Literal(alias)}] = {Literal(parameter.Name)},");
                }
            }
            source.AppendLine("            });");
            source.AppendLine();
        }

        source.AppendLine("    }");
        source.AppendLine("}");

        return source.ToString();
    }

    private static string Literal(string value) =>
        SyntaxFactory.Literal(value).ToFullString();

    private sealed record Entry(
        string InvocationName,
        string ProcessorType,
        IReadOnlyList<string> Aliases,
        IReadOnlyList<Parameter> Parameters);

    private sealed record Parameter(
        string Name,
        string Type,
        string Help,
        bool Required,
        IReadOnlyList<string> Aliases,
        IReadOnlyList<string> AllowedValues);
}
