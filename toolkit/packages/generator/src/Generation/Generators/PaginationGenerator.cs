using Ace.Generator.Model;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Ace.Generator.Generators;

/// <summary>Emits one extension-local pagination helper from the authoritative codegen template.</summary>
internal sealed class PaginationGenerator : IArtifactGenerator
{
    private const string ResourceName = "Ace.Generator.Templates.Pagination.cs";

    public string Name => "pagination";

    public IEnumerable<GeneratedFile> Produce(GenerationContext context)
    {
        context.CancellationToken.ThrowIfCancellationRequested();
        using Stream stream = typeof(PaginationGenerator).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException($"Missing pagination template resource '{ResourceName}'.");
        using var reader = new StreamReader(stream);
        CompilationUnitSyntax template = CSharpSyntaxTree.ParseText(reader.ReadToEnd()).GetCompilationUnitRoot();
        var sourceNamespace = template.Members.OfType<FileScopedNamespaceDeclarationSyntax>().Single();
        var sourceClass = sourceNamespace.Members.OfType<ClassDeclarationSyntax>().Single();
        ClassDeclarationSyntax helper = sourceClass
            .WithIdentifier(Identifier(context.Placement.PaginationTypeName))
            .WithModifiers(TokenList(Token(SyntaxKind.InternalKeyword), Token(SyntaxKind.StaticKeyword)));
        FileScopedNamespaceDeclarationSyntax targetNamespace = sourceNamespace
            .WithName(ParseName(context.Placement.ProcessorsNamespace))
            .AddUsings(UsingDirective(ParseName("Microsoft.Azure.Azclips.ExtensionRuntime")))
            .WithMembers(SingletonList<MemberDeclarationSyntax>(helper));
        CompilationUnitSyntax output = template
            .WithMembers(SingletonList<MemberDeclarationSyntax>(targetNamespace))
            .NormalizeWhitespace()
            .FixNormalizerSpacing();

        yield return new GeneratedFile(
            context.Placement.ProcessorFile(context.Placement.PaginationTypeName),
            "// <auto-generated /> Emitted by Ace.Generator (pagination helper).\n#nullable enable\n" + output.ToFullString() + "\n",
            context.Placement.PaginationTypeName);
    }
}
