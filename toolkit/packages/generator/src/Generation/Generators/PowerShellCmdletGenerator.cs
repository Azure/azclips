using System.Globalization;
using System.Text;
using Ace.Generator.Model;
using Ace.Generator.Model.Ir;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Ace.Generator.Generators;

/// <summary>
/// Emits the private, PowerShell-discoverable cmdlet variants that the build-time exporter reflects.
/// One class represents one <see cref="PSParameterSetAttribute"/> and uses the same private invocation
/// name as the corresponding <see cref="ExtensionIndexGenerator"/> entry.
/// </summary>
internal sealed class PowerShellCmdletGenerator : IArtifactGenerator
{
    private const string Banner = "// <auto-generated /> Emitted from IR by Ace.Generator.";

    public string Name => "powershell-cmdlets";

    public IEnumerable<string> Clean(GenerationContext context) => ["Cmdlets"];

    public IEnumerable<GeneratedFile> Produce(GenerationContext context)
    {
        PS? ps = context.Ir.Ps;
        if (ps is null)
        {
            yield break;
        }

        PSCommandAttribute[] commands = [.. ps.Commands.Where(command => command.Hidden != true)];
        if (commands.Length == 0)
        {
            yield break;
        }

        yield return new GeneratedFile(
            "Cmdlets/GeneratedCmdletBase.cs",
            EmitBase(context.Options),
            "GeneratedCmdletBase");
        yield return new GeneratedFile(
            "Cmdlets/PowerShellAttributes.cs",
            EmitAttributes(context.Options),
            "GeneratedAttribute");

        IReadOnlyDictionary<string, IRTypeRef> types = TypeIndex(context.Ir);
        IReadOnlyDictionary<string, IReadOnlyList<string>> enums = EnumIndex(context.Ir);
        IReadOnlyDictionary<string, IROperation> operations = context.Ir.Operations
            .Where(operation => operation.Id is not null)
            .ToDictionary(operation => Key(operation.Id), StringComparer.Ordinal);
        foreach (PSCommandAttribute command in commands)
        {
            string extensionName = ExtensionName(ps, command, context.Options);
            foreach (PSParameterSetAttribute set in command.ParameterSets)
            {
                context.CancellationToken.ThrowIfCancellationRequested();
                operations.TryGetValue(Key(set.SourceOperationId), out IROperation? operation);
                string privateNoun = command.ParameterSets.Count > 1
                    ? $"{command.Noun}_{set.Name}"
                    : command.Noun;
                string className = command.ParameterSets.Count > 1
                    ? $"{command.Verb.Identifier()}{command.Noun.Identifier()}_{set.Name.Identifier()}"
                    : $"{command.Verb.Identifier()}{command.Noun.Identifier()}";
                yield return new GeneratedFile(
                    $"Cmdlets/{className}.cs",
                    Emit(context.Options, command, set, operation, privateNoun, className, extensionName, types, enums),
                    className);
            }
        }
    }

    private static string Emit(
        GeneratorOptions options,
        PSCommandAttribute command,
        PSParameterSetAttribute set,
        IROperation? operation,
        string privateNoun,
        string className,
        string extensionName,
        IReadOnlyDictionary<string, IRTypeRef> types,
        IReadOnlyDictionary<string, IReadOnlyList<string>> enums)
    {
        PSParameterAttribute[] parameters = [.. command.Parameters
            .Where(parameter => TakesPart(parameter, set.Name))];
        var members = parameters
            .Select(parameter => PropertyFor(parameter, set.Name, types, enums))
            .Where(property => property is not null)
            .Cast<MemberDeclarationSyntax>()
            .Concat(
            [
                StringProperty("ExtensionName", extensionName),
                StringProperty("InvocationName", $"{command.Verb}-{privateNoun}"),
                ParameterNamesProperty(parameters),
            ])
            .ToArray();

        ClassDeclarationSyntax cmdlet = ClassDeclaration(className)
            .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.SealedKeyword))
            .WithBaseList(BaseList(SingletonSeparatedList<BaseTypeSyntax>(SimpleBaseType(ParseTypeName("GeneratedCmdletBase")))))
            .AddAttributeLists(CmdletAttribute(command, set.Name, privateNoun))
            .AddAttributeLists(MarkerAttribute("Generated"))
            .AddMembers(members)
            .WithLeadingXmlDoc(command.Description ?? command.Summary);

        if (!string.IsNullOrWhiteSpace(command.Description ?? command.Summary))
        {
            cmdlet = cmdlet.AddAttributeLists(
                StringArrayAttribute("Description", [command.Description ?? command.Summary!]));
        }

        string? httpPath = command.HttpPath?.Path ?? operation?.PathTemplate;
        string? apiVersion = command.HttpPath?.ApiVersion ?? operation?.ApiVersion?.Value;
        if (!string.IsNullOrWhiteSpace(httpPath))
        {
            cmdlet = cmdlet.AddAttributeLists(
                NamedStringAttribute(
                    "HttpPath",
                    ("Path", httpPath),
                    ("ApiVersion", apiVersion)));
        }

        if (command.OutputTypes.Count > 0)
        {
            cmdlet = cmdlet.AddAttributeLists(OutputTypeAttribute(options.RootNamespace, command.OutputTypes));
        }

        if (command.Alias is { Count: > 0 })
        {
            cmdlet = cmdlet.AddAttributeLists(StringArrayAttribute("Alias", command.Alias));
        }

        CompilationUnitSyntax unit = CompilationUnit()
            .AddUsings(
                UsingDirective(ParseName("System.Collections.Generic")),
                UsingDirective(ParseName("System.Management.Automation")),
                UsingDirective(ParseName(options.RootNamespace)),
                UsingDirective(ParseName($"{options.RootNamespace}.Models")))
            .AddMembers(
                FileScopedNamespaceDeclaration(ParseName($"{options.RootNamespace}.Cmdlets")).AddMembers(cmdlet))
            .NormalizeWhitespace();

        var source = new StringBuilder();
        source.AppendLine(Banner);
        source.AppendLine();
        source.Append(unit.ToFullString());
        source.AppendLine();
        return source.ToString();
    }

    private static string EmitAttributes(GeneratorOptions options)
    {
        ClassDeclarationSyntax description = AttributeClass(
            "DescriptionAttribute",
            "AttributeTargets.Class",
            AutoProperty("string", "Description", setter: false),
            ConstructorDeclaration("DescriptionAttribute")
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .AddParameterListParameters(Parameter(Identifier("description")).WithType(ParseTypeName("string")))
                .WithRawBody("Description = description;"));

        ClassDeclarationSyntax generated = AttributeClass("GeneratedAttribute", "AttributeTargets.Class");
        ClassDeclarationSyntax doNotExport = AttributeClass(
            "DoNotExportAttribute",
            "AttributeTargets.Class | AttributeTargets.Property");
        ClassDeclarationSyntax httpPath = AttributeClass(
            "HttpPathAttribute",
            "AttributeTargets.Class",
            AutoProperty("string", "Path"),
            AutoProperty("string", "ApiVersion"));
        ClassDeclarationSyntax completer = AttributeClass(
            "CompleterInfoAttribute",
            "AttributeTargets.Class | AttributeTargets.Property",
            AutoProperty("string", "Script"),
            AutoProperty("string", "Name"),
            AutoProperty("string", "Description"));
        ClassDeclarationSyntax defaultInfo = AttributeClass(
            "DefaultInfoAttribute",
            "AttributeTargets.Property",
            AutoProperty("string", "Script"),
            AutoProperty("string", "Name"),
            AutoProperty("string", "Description"),
            AutoProperty("string", "SetCondition"));

        CompilationUnitSyntax unit = CompilationUnit()
            .AddUsings(UsingDirective(ParseName("System")))
            .AddMembers(
                FileScopedNamespaceDeclaration(ParseName(options.RootNamespace))
                    .AddMembers(description, generated, doNotExport, httpPath, completer, defaultInfo))
            .NormalizeWhitespace();

        var source = new StringBuilder();
        source.AppendLine(Banner);
        source.AppendLine();
        source.Append(unit.ToFullString());
        source.AppendLine();
        return source.ToString();
    }

    private static ClassDeclarationSyntax AttributeClass(
        string name,
        string targets,
        params MemberDeclarationSyntax[] members) =>
        ClassDeclaration(name)
            .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.SealedKeyword))
            .WithBaseList(BaseList(SingletonSeparatedList<BaseTypeSyntax>(SimpleBaseType(ParseTypeName("Attribute")))))
            .AddAttributeLists(
                AttributeList(
                    SingletonSeparatedList(
                        Attribute(IdentifierName("AttributeUsage"))
                            .WithArgumentList(
                                AttributeArgumentList(
                                    SingletonSeparatedList(AttributeArgument(ParseExpression(targets))))))))
            .AddMembers(members);

    private static PropertyDeclarationSyntax AutoProperty(string type, string name, bool setter = true)
    {
        var accessors = new List<AccessorDeclarationSyntax>
        {
            AccessorDeclaration(SyntaxKind.GetAccessorDeclaration).WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
        };
        if (setter)
        {
            accessors.Add(AccessorDeclaration(SyntaxKind.SetAccessorDeclaration).WithSemicolonToken(Token(SyntaxKind.SemicolonToken)));
        }

        PropertyDeclarationSyntax property = PropertyDeclaration(ParseTypeName(type), name)
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .AddAccessorListAccessors([.. accessors]);
        return setter
            ? property.WithInitializer(EqualsValueClause(StringExpression(string.Empty)))
                .WithSemicolonToken(Token(SyntaxKind.SemicolonToken))
            : property;
    }

    private static string EmitBase(GeneratorOptions options)
    {
        ClassDeclarationSyntax cmdletBase = ClassDeclaration("GeneratedCmdletBase")
            .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.AbstractKeyword))
            .WithBaseList(BaseList(SingletonSeparatedList<BaseTypeSyntax>(SimpleBaseType(ParseTypeName("PSCmdlet")))))
            .AddMembers(
                FieldDeclaration(
                        VariableDeclaration(ParseTypeName("CancellationTokenSource"))
                            .AddVariables(
                                VariableDeclarator("cancellationTokenSource")
                                    .WithInitializer(EqualsValueClause(ParseExpression("new CancellationTokenSource()")))))
                    .AddModifiers(Token(SyntaxKind.PrivateKeyword), Token(SyntaxKind.ReadOnlyKeyword)),
                AbstractProperty("string", "ExtensionName"),
                AbstractProperty("string", "InvocationName"),
                AbstractProperty("IReadOnlySet<string>", "ParameterNames"),
                MethodDeclaration(ParseTypeName("void"), "ProcessRecord")
                    .AddModifiers(Token(SyntaxKind.ProtectedKeyword), Token(SyntaxKind.OverrideKeyword))
                    .WithRawBody(
                        """
                        var parameters = new Dictionary<string, object>(StringComparer.OrdinalIgnoreCase);
                        foreach (var parameter in MyInvocation.BoundParameters)
                        {
                            if (ParameterNames.Contains(parameter.Key))
                            {
                                parameters[parameter.Key] = parameter.Value;
                            }
                        }

                        var streams = CmdletOutputStreamsFactory.Create(this, $"{ExtensionName}Error", ErrorCategory.NotSpecified, enumerateOutput: true);
                        var engine = AzclipsServiceProvider.GetRequiredService<IEngine>();
                        var invocation = new CommandInvocation(
                            ExtensionName,
                            InvocationName,
                            parameters,
                            false,
                            MyInvocation.MyCommand.ModuleName,
                            MyInvocation.MyCommand.Version?.ToString());
                        using ISession session = engine.OpenExecutionSession(invocation, streams, cancellationTokenSource.Token);
                        session.Run();
                        """),
                MethodDeclaration(ParseTypeName("void"), "StopProcessing")
                    .AddModifiers(Token(SyntaxKind.ProtectedKeyword), Token(SyntaxKind.OverrideKeyword))
                    .WithExpressionBody(ArrowExpressionClause(ParseExpression("cancellationTokenSource.Cancel()")))
                    .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
                MethodDeclaration(ParseTypeName("void"), "EndProcessing")
                    .AddModifiers(Token(SyntaxKind.ProtectedKeyword), Token(SyntaxKind.OverrideKeyword))
                    .WithExpressionBody(ArrowExpressionClause(ParseExpression("cancellationTokenSource.Dispose()")))
                    .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)));

        CompilationUnitSyntax unit = CompilationUnit()
            .AddUsings(
                UsingDirective(ParseName("System")),
                UsingDirective(ParseName("System.Collections.Generic")),
                UsingDirective(ParseName("System.Management.Automation")),
                UsingDirective(ParseName("System.Threading")),
                UsingDirective(ParseName("Core.Abstractions")),
                UsingDirective(ParseName("Core.DependencyInjection")),
                UsingDirective(ParseName("Microsoft.Azure.Azclips.Cmdlets.Common")))
            .AddMembers(
                FileScopedNamespaceDeclaration(ParseName($"{options.RootNamespace}.Cmdlets")).AddMembers(cmdletBase))
            .NormalizeWhitespace();

        var source = new StringBuilder();
        source.AppendLine(Banner);
        source.AppendLine();
        source.Append(unit.ToFullString());
        source.AppendLine();
        return source.ToString();
    }

    private static PropertyDeclarationSyntax AbstractProperty(string type, string name) =>
        PropertyDeclaration(ParseTypeName(type), name)
            .AddModifiers(Token(SyntaxKind.ProtectedKeyword), Token(SyntaxKind.AbstractKeyword))
            .AddAccessorListAccessors(
                AccessorDeclaration(SyntaxKind.GetAccessorDeclaration).WithSemicolonToken(Token(SyntaxKind.SemicolonToken)));

    private static PropertyDeclarationSyntax StringProperty(string name, string value) =>
        PropertyDeclaration(ParseTypeName("string"), name)
            .AddModifiers(Token(SyntaxKind.ProtectedKeyword), Token(SyntaxKind.OverrideKeyword))
            .WithExpressionBody(ArrowExpressionClause(StringExpression(value)))
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));

    private static PropertyDeclarationSyntax ParameterNamesProperty(IReadOnlyList<PSParameterAttribute> parameters)
    {
        string values = string.Join(", ", parameters.Select(parameter => Literal(parameter.Name).ToFullString()));
        return PropertyDeclaration(ParseTypeName("IReadOnlySet<string>"), "ParameterNames")
            .AddModifiers(Token(SyntaxKind.ProtectedKeyword), Token(SyntaxKind.OverrideKeyword))
            .WithExpressionBody(
                ArrowExpressionClause(ParseExpression($"new HashSet<string>(StringComparer.OrdinalIgnoreCase) {{ {values} }}")))
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
    }

    private static string ExtensionName(PS ps, PSCommandAttribute command, GeneratorOptions options)
    {
        string publicName = $"{command.Verb}-{command.Noun}";
        return ps.Modules.FirstOrDefault(module => module.CmdletsToExport.Contains(publicName, StringComparer.OrdinalIgnoreCase))?.Name
            ?? options.RootNamespace.Split('.', StringSplitOptions.RemoveEmptyEntries).Last();
    }

    private static bool TakesPart(PSParameterAttribute parameter, string setName) =>
        parameter.ParameterSets is { } sets
            ? sets.ContainsKey(setName)
            : parameter.ParameterSetName is null || parameter.ParameterSetName == setName;

    private static PropertyDeclarationSyntax? PropertyFor(
        PSParameterAttribute parameter,
        string setName,
        IReadOnlyDictionary<string, IRTypeRef> types,
        IReadOnlyDictionary<string, IReadOnlyList<string>> enums)
    {
        PSParameterSetOverride? over = null;
        if (parameter.ParameterSets is { } sets)
        {
            if (!sets.TryGetValue(setName, out over))
            {
                return null;
            }
        }
        else if (parameter.ParameterSetName is { } only && only != setName)
        {
            return null;
        }

        string type = "object";
        if (parameter.Identity != true
            && parameter.SourceParameterId is { } sourceId
            && types.TryGetValue(Key(sourceId), out IRTypeRef? typeRef))
        {
            type = Render(typeRef);
        }

        var property = PropertyDeclaration(ParseTypeName(type), Identifier(parameter.Name.Identifier()))
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .AddAccessorListAccessors(
                AccessorDeclaration(SyntaxKind.GetAccessorDeclaration).WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
                AccessorDeclaration(SyntaxKind.SetAccessorDeclaration).WithSemicolonToken(Token(SyntaxKind.SemicolonToken)))
            .AddAttributeLists(ParameterAttribute(parameter, over, setName))
            .WithLeadingXmlDoc(over?.HelpMessage ?? parameter.HelpMessage);

        if (parameter.Alias is { Count: > 0 })
        {
            property = property.AddAttributeLists(StringArrayAttribute("Alias", parameter.Alias));
        }

        if (parameter.Hidden == true)
        {
            property = property.AddAttributeLists(MarkerAttribute("DoNotExport"));
        }

        if (parameter.Completer is { } completer)
        {
            property = property.AddAttributeLists(
                NamedStringAttribute(
                    "CompleterInfo",
                    ("Script", completer.Script),
                    ("Name", completer.Name),
                    ("Description", completer.Description)));
        }

        if (parameter.DefaultValue is { } defaultValue)
        {
            property = property.AddAttributeLists(
                NamedStringAttribute(
                    "DefaultInfo",
                    ("Script", defaultValue.Script),
                    ("Name", defaultValue.Name),
                    ("Description", defaultValue.Description),
                    ("SetCondition", defaultValue.SetCondition)));
        }

        if (parameter.SourceParameterId is { } enumSourceId
            && types.TryGetValue(Key(enumSourceId), out IRTypeRef? sourceType)
            && sourceType is IRTypeRefEnum enumType
            && enums.TryGetValue(Key(enumType.Id), out IReadOnlyList<string>? values))
        {
            property = property.AddAttributeLists(StringArrayAttribute("ValidateSet", values));
        }

        return property;
    }

    private static AttributeListSyntax CmdletAttribute(
        PSCommandAttribute command,
        string setName,
        string privateNoun)
    {
        var arguments = new List<AttributeArgumentSyntax>
        {
            StringArgument(command.Verb),
            StringArgument(privateNoun),
            NamedArgument("DefaultParameterSetName", StringExpression(setName)),
        };

        if (command.SupportsShouldProcess)
        {
            arguments.Add(NamedArgument("SupportsShouldProcess", TrueLiteral()));
        }

        if (command.ConfirmImpact is { } impact)
        {
            arguments.Add(NamedArgument("ConfirmImpact", ParseExpression($"ConfirmImpact.{impact}")));
        }

        if (command.HelpUri is { Length: > 0 } helpUri)
        {
            arguments.Add(NamedArgument("HelpUri", StringExpression(helpUri)));
        }

        return AttributeList(
            SingletonSeparatedList(
                Attribute(IdentifierName("Cmdlet"))
                    .WithArgumentList(AttributeArgumentList(SeparatedList(arguments)))));
    }

    private static AttributeListSyntax OutputTypeAttribute(string rootNamespace, IReadOnlyList<IRId> outputTypes) =>
        StringArrayAttribute(
            "OutputType",
            outputTypes.Select(id => $"{rootNamespace}.Models.{id.Name.Identifier()}").ToArray());

    private static AttributeListSyntax ParameterAttribute(
        PSParameterAttribute parameter,
        PSParameterSetOverride? over,
        string setName)
    {
        var arguments = new List<AttributeArgumentSyntax>
        {
            NamedArgument("ParameterSetName", StringExpression(setName)),
            NamedArgument("Mandatory", (over?.Mandatory ?? parameter.Mandatory ?? false) ? TrueLiteral() : FalseLiteral()),
        };

        int? position = over?.Position ?? parameter.Position;
        if (position is not null)
        {
            arguments.Add(NamedArgument("Position", LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(position.Value))));
        }

        if (parameter.ValueFromPipeline == true)
        {
            arguments.Add(NamedArgument("ValueFromPipeline", TrueLiteral()));
        }

        if (parameter.ValueFromPipelineByPropertyName == true)
        {
            arguments.Add(NamedArgument("ValueFromPipelineByPropertyName", TrueLiteral()));
        }

        if (parameter.Hidden == true)
        {
            arguments.Add(NamedArgument("DontShow", TrueLiteral()));
        }

        string? help = over?.HelpMessage ?? parameter.HelpMessage;
        if (!string.IsNullOrWhiteSpace(help))
        {
            arguments.Add(NamedArgument("HelpMessage", StringExpression(help)));
        }

        return AttributeList(
            SingletonSeparatedList(
                Attribute(IdentifierName("Parameter"))
                    .WithArgumentList(AttributeArgumentList(SeparatedList(arguments)))));
    }

    private static AttributeListSyntax StringArrayAttribute(string name, IReadOnlyList<string> values) =>
        AttributeList(
            SingletonSeparatedList(
                Attribute(IdentifierName(name))
                    .WithArgumentList(AttributeArgumentList(SeparatedList(values.Select(StringArgument))))));

    private static AttributeListSyntax MarkerAttribute(string name) =>
        AttributeList(SingletonSeparatedList(Attribute(IdentifierName(name))));

    private static AttributeListSyntax NamedStringAttribute(
        string name,
        params (string Name, string? Value)[] properties) =>
        AttributeList(
            SingletonSeparatedList(
                Attribute(IdentifierName(name))
                    .WithArgumentList(
                        AttributeArgumentList(
                            SeparatedList(
                                properties
                                    .Where(property => property.Value is not null)
                                    .Select(property => NamedArgument(property.Name, StringExpression(property.Value!))))))));

    private static AttributeArgumentSyntax StringArgument(string value) =>
        AttributeArgument(StringExpression(value));

    private static AttributeArgumentSyntax NamedArgument(string name, ExpressionSyntax expression) =>
        AttributeArgument(expression).WithNameEquals(NameEquals(IdentifierName(name)));

    private static LiteralExpressionSyntax StringExpression(string value) =>
        LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(value));

    private static LiteralExpressionSyntax TrueLiteral() => LiteralExpression(SyntaxKind.TrueLiteralExpression);

    private static LiteralExpressionSyntax FalseLiteral() => LiteralExpression(SyntaxKind.FalseLiteralExpression);

    private static Dictionary<string, IRTypeRef> TypeIndex(IRDocument ir)
    {
        var index = new Dictionary<string, IRTypeRef>(StringComparer.Ordinal);
        foreach (IROperation operation in ir.Operations)
        {
            foreach (IRParameter parameter in operation.PathParameters
                .Concat(operation.QueryParameters)
                .Concat(operation.HeaderParameters))
            {
                if (parameter.Id is not null && parameter.Type is not null)
                {
                    index[Key(parameter.Id)] = parameter.Type;
                }
            }
        }

        foreach (IRModel model in ir.Models)
        {
            foreach (IRProperty property in model.Properties)
            {
                if (property.Id is not null)
                {
                    index[Key(property.Id)] = IrTypeMapper.ToTypeRef(property);
                }
            }
        }

        return index;
    }

    private static Dictionary<string, IReadOnlyList<string>> EnumIndex(IRDocument ir)
    {
        var index = new Dictionary<string, IReadOnlyList<string>>(StringComparer.Ordinal);
        foreach (IREnum @enum in ir.Enums)
        {
            if (@enum.Id is not null)
            {
                index[Key(@enum.Id)] = [.. @enum.Members.Select(member => member.Value?.ToString() ?? member.Name)];
            }
        }

        return index;
    }

    private static string Render(IRTypeRef type) => type switch
    {
        IRTypeRefEnum => "string",
        IRTypeRefArray array => $"IList<{Render(array.Element)}>",
        IRTypeRefDictionary dictionary => $"IDictionary<string, {Render(dictionary.Value)}>",
        _ => IrTypeMapper.ToCSharp(type),
    };

    private static string Key(IRId id) =>
        string.Create(CultureInfo.InvariantCulture, $"{id.Module}|{string.Join('.', id.Namespace)}|{id.Name}");
}
