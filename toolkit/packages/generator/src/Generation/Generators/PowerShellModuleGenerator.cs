using System.Text;
using Ace.Generator.Model;
using Ace.Generator.Model.Ir;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Ace.Generator.Generators;

/// <summary>Emits module-wide PowerShell metadata and the optional synthesized identity type.</summary>
internal sealed class PowerShellModuleGenerator : IArtifactGenerator
{
    public string Name => "powershell-module";

    public IEnumerable<GeneratedFile> Produce(GenerationContext context)
    {
        IRTargetDialectPs? module = context.Ir.Target?.Dialect?.Ps;
        if (module is not null)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            yield return ModuleMetadata(context, module);
        }

        foreach (TransformedIRSharedTypes identity in context.Ir.SharedTypes.Where(
            sharedType => string.Equals(sharedType.Kind, "identity", StringComparison.Ordinal)))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            yield return Identity(context, identity);
        }
    }

    private static GeneratedFile ModuleMetadata(GenerationContext context, IRTargetDialectPs module)
    {
        string sourceId = context.Ir.Sources.FirstOrDefault()?.Id ?? module.Name;
        string[] cmdlets = [.. context.Ir.Commands
            .Where(command => command.Dialect?.Ps is { Hidden: not true } && command.Access != IRCommandAccess.Internal)
            .Select(command => $"{command.Dialect!.Ps!.Verb}-{command.Dialect.Ps.Noun}")
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)];

        var arguments = new List<string>
        {
            StringLiteral(module.Name),
            StringLiteral(sourceId),
        };
        if (module.Description is not null)
        {
            arguments.Add($"Description = {StringLiteral(module.Description)}");
        }
        if (cmdlets.Length > 0)
        {
            arguments.Add($"CmdletsToExport = new string[] {{ {string.Join(", ", cmdlets.Select(StringLiteral))} }}");
        }

        string contents =
            "// <auto-generated /> Emitted from IR by Ace.Generator.\n" +
            "using Core.Abstractions;\n\n" +
            $"[assembly: PSModule({string.Join(", ", arguments)})]\n";
        return new GeneratedFile("Properties/PowerShellAssemblyInfo.cs", contents);
    }

    private static GeneratedFile Identity(
        GenerationContext context,
        TransformedIRSharedTypes identity)
    {
        var contents = new StringBuilder();
        contents.AppendLine("// <auto-generated /> Emitted from IR by Ace.Generator.");
        contents.AppendLine("#nullable enable");
        contents.AppendLine();
        contents.AppendLine("using Core.Abstractions;");
        contents.AppendLine();
        contents.Append("namespace ").Append(context.Placement.ModelsNamespace).AppendLine(";");
        contents.AppendLine();
        contents.Append("[PSIdentity(").Append(StringLiteral(identity.Name)).AppendLine(")]");
        contents.Append("public partial class ").Append(identity.Name).AppendLine();
        contents.AppendLine("{");
        foreach (TransformedIRSharedTypesProperties property in identity.Properties)
        {
            IRParameter? source = SourceParameter(context.Ir, property.SourceParameters.FirstOrDefault());
            string type = source is null ? "string" : IrTypeMapper.ToCSharp(source.Type, context.Index);
            contents.Append("    [PSIdentityProperty(").Append(StringLiteral(property.Name));
            if (property.Description is not null)
            {
                contents.Append(", HelpMessage = ").Append(StringLiteral(property.Description));
            }
            contents.AppendLine(")] ");
            contents.Append("    public ").Append(type).Append("? ").Append(property.Name)
                .AppendLine(" { get; set; }");
            contents.AppendLine();
        }
        contents.AppendLine("}");

        string path = $"{context.Placement.ModelsDirectory}/{identity.Name}.cs";
        return new GeneratedFile(path, contents.ToString(), identity.Name);
    }

    private static IRParameter? SourceParameter(TransformedIR ir, IRId? id)
    {
        if (id is null)
        {
            return null;
        }

        return ir.Operations
            .SelectMany(operation => operation.PathParameters)
            .FirstOrDefault(parameter => parameter.Id is not null && IrIds.Equal(parameter.Id, id));
    }

    private static string StringLiteral(string value) => SymbolDisplay.FormatLiteral(value, true);
}