using Ace.Generator;
using Ace.Generator.Model;
using Ace.Generator.Model.Ir;

namespace Ace.Generator.Generators;

/// <summary>
/// Emits C# project scaffolding: the <c>.csproj</c>, assembly metadata, and any
/// static resources — the non-source artifacts a compilable generated client
/// needs. Scaffold: a minimal SDK-style <c>.csproj</c>.
/// </summary>
/// <remarks>
/// TODO — real project: runtime package references, target framework, nullable /
/// langversion, assembly metadata, embedded resources.
/// </remarks>
internal sealed class ProjectStubGenerator : IArtifactGenerator
{
    public string Name => "stub";

    public IEnumerable<GeneratedFile> Produce(GenerationContext context)
    {
        context.CancellationToken.ThrowIfCancellationRequested();

        string projectName = context.Options.RootNamespace;
        yield return new GeneratedFile($"{projectName}.csproj", Csproj());
    }

    private static string Csproj() =>
        """
        <!-- <auto-generated /> Scaffold stub — replace with the real project template. -->
        <Project Sdk="Microsoft.NET.Sdk">

          <PropertyGroup>
            <TargetFramework>net10.0</TargetFramework>
            <Nullable>enable</Nullable>
            <ImplicitUsings>enable</ImplicitUsings>
            <LangVersion>latest</LangVersion>
          </PropertyGroup>

        </Project>

        """;
}
