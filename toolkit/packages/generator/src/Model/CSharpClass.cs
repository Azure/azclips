using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Ace.Generator.Model;

internal class CSharpClass
{
    string Namespace { get; }
    string Name { get; }
    string? BaseType { get; }
    bool IsAbstract { get; }

    private readonly ClassDeclarationSyntax definition = null!;
    private readonly CompilationUnitSyntax unit = null!;

    internal CSharpClass(string @namespace, string name, string? baseType = null, bool isAbstract = false)
    {
        Namespace = @namespace;
        Name = name;
        BaseType = baseType;
        IsAbstract = isAbstract;
        definition = ClassDeclaration(name).AddModifiers(Token(SyntaxKind.PublicKeyword));
        if (isAbstract)
        {
            definition = definition.AddModifiers(Token(SyntaxKind.AbstractKeyword));
        }
        definition = definition.AddModifiers(Token(SyntaxKind.PartialKeyword));
        if (baseType is not null)
        {
            definition = definition.WithBaseList(BaseList(SingletonSeparatedList<BaseTypeSyntax>(SimpleBaseType(ParseTypeName(baseType)))));
        }
        unit = CompilationUnit()
            .AddMembers(FileScopedNamespaceDeclaration(ParseName(@namespace)).AddMembers(definition))
            .NormalizeWhitespace();
    }

    private const string Banner = "// <auto-generated /> Scaffold stub — replace with real emission.";

    /// <summary>
    /// Render a single-class compilation unit:
    /// <c>namespace ns; public [abstract] partial class name [: baseType] { }</c>.
    /// </summary>
    internal string Source()
    {
        return Banner + Environment.NewLine + unit.ToFullString() + Environment.NewLine;
    }
}