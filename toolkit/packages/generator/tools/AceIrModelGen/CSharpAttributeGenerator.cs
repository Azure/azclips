using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static Microsoft.CodeAnalysis.CSharp.SyntaxFactory;

namespace Ace.Ir.CodeGen;

internal sealed class CSharpAttributeGenerator
{
    private readonly JsonDocument _document;
    private readonly JsonElement _definitions;
    private readonly string _namespace;

    public CSharpAttributeGenerator(string schemaJson, string @namespace)
    {
        _document = JsonDocument.Parse(schemaJson);
        _definitions = _document.RootElement.GetProperty("definitions");
        _namespace = @namespace;
    }

    public string Generate()
    {
        var attributes = new List<MemberDeclarationSyntax>();
        foreach (JsonProperty definition in _definitions.EnumerateObject())
        {
            if (definition.Value.TryGetProperty("x-csharp-attribute", out JsonElement projection))
            {
                attributes.AddRange(projection.GetProperty("enums").EnumerateArray().Select(EmitEnum));
                attributes.Add(EmitAttribute(definition.Value, projection));
            }
        }

        CompilationUnitSyntax unit = CompilationUnit()
            .AddUsings(UsingDirective(ParseName("System")))
            .AddMembers(FileScopedNamespaceDeclaration(ParseName(_namespace)).AddMembers([.. attributes]))
            .NormalizeWhitespace();

        var output = new StringBuilder();
        output.AppendLine("// <auto-generated>");
        output.AppendLine("//     Generated by AceIrModelGen from the IR JSON Schema's x-csharp-attribute projections.");
        output.AppendLine("//     Do not edit by hand; re-run the generator instead.");
        output.AppendLine("// </auto-generated>");
        output.AppendLine("#nullable enable");
        output.AppendLine();
        output.Append(unit.ToFullString());
        output.AppendLine();
        return output.ToString();
    }

    private static ClassDeclarationSyntax EmitAttribute(JsonElement schema, JsonElement projection)
    {
        string name = projection.GetProperty("name").GetString()!;
        var constructorParameters = new List<(string Name, string Type, string PropertyName)>();

        foreach (JsonElement parameter in projection.GetProperty("constructor").EnumerateArray())
        {
            string parameterName = parameter.GetProperty("name").GetString()!;
            string propertyName = Pascal(parameterName);
            string type = parameter.TryGetProperty("source", out JsonElement source)
                ? AttributeType(schema.GetProperty("properties").GetProperty(source.GetString()!))
                : AttributeType(parameter.GetProperty("type").GetString()!);
            constructorParameters.Add((parameterName, type, propertyName));
        }

        ConstructorDeclarationSyntax constructor = ConstructorDeclaration(name)
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .AddParameterListParameters([.. constructorParameters.Select(parameter =>
                Parameter(Identifier(parameter.Name)).WithType(ParseTypeName(parameter.Type)))])
            .WithBody(Block(constructorParameters.Select(parameter =>
                ExpressionStatement(AssignmentExpression(
                    SyntaxKind.SimpleAssignmentExpression,
                    IdentifierName(parameter.PropertyName),
                    IdentifierName(parameter.Name))))));

        var members = new List<MemberDeclarationSyntax> { constructor };
        members.AddRange(constructorParameters.Select(parameter => Property(parameter.Type, parameter.PropertyName, settable: false)));

        foreach (JsonElement property in projection.GetProperty("properties").EnumerateArray())
        {
            string propertyName = property.GetProperty("name").GetString()!;
            string type = property.TryGetProperty("type", out JsonElement explicitType)
                ? ExplicitAttributeType(explicitType)
                : AttributeType(schema.GetProperty("properties").GetProperty(property.GetProperty("source").GetString()!));
            string? defaultValue = property.TryGetProperty("default", out JsonElement value) ? value.GetString() : null;
            bool required = property.TryGetProperty("required", out JsonElement requiredElement) && requiredElement.GetBoolean();
            members.Add(Property(type, propertyName, settable: true, defaultValue, required));
        }

        return ClassDeclaration(name)
            .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.SealedKeyword))
            .WithBaseList(BaseList(SingletonSeparatedList<BaseTypeSyntax>(SimpleBaseType(IdentifierName("Attribute")))))
            .WithAttributeLists(SingletonList(AttributeUsage(projection)))
            .AddMembers([.. members]);
    }

    private static EnumDeclarationSyntax EmitEnum(JsonElement projection) =>
        EnumDeclaration(projection.GetProperty("name").GetString()!)
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .AddMembers([.. projection.GetProperty("members").EnumerateArray().Select(member =>
                EnumMemberDeclaration(member.GetString()!))]);

    private static PropertyDeclarationSyntax Property(string type, string name, bool settable, string? defaultValue = null, bool required = false)
    {
        var accessors = new List<AccessorDeclarationSyntax>
        {
            AccessorDeclaration(SyntaxKind.GetAccessorDeclaration).WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
        };
        if (settable)
        {
            accessors.Add(AccessorDeclaration(SyntaxKind.SetAccessorDeclaration).WithSemicolonToken(Token(SyntaxKind.SemicolonToken)));
        }

        PropertyDeclarationSyntax property = PropertyDeclaration(ParseTypeName(type), Identifier(name))
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .WithAccessorList(AccessorList(List(accessors)));
        if (required)
        {
            property = property.AddModifiers(Token(SyntaxKind.RequiredKeyword));
        }
        return defaultValue is null
            ? property
            : property.WithInitializer(EqualsValueClause(ParseExpression(defaultValue)))
                .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
    }

    private static AttributeListSyntax AttributeUsage(JsonElement projection)
    {
        string targets = string.Join(
            " | ",
            projection.GetProperty("targets").EnumerateArray().Select(target => $"AttributeTargets.{target.GetString()}"));
        bool allowMultiple = projection.GetProperty("allowMultiple").GetBoolean();
        bool inherited = projection.GetProperty("inherited").GetBoolean();
        return AttributeList(SingletonSeparatedList(
            Attribute(IdentifierName("AttributeUsage"))
                .WithArgumentList(AttributeArgumentList(SeparatedList<AttributeArgumentSyntax>(
                [
                    AttributeArgument(ParseExpression(targets)),
                    AttributeArgument(LiteralExpression(allowMultiple ? SyntaxKind.TrueLiteralExpression : SyntaxKind.FalseLiteralExpression))
                        .WithNameEquals(NameEquals("AllowMultiple")),
                    AttributeArgument(LiteralExpression(inherited ? SyntaxKind.TrueLiteralExpression : SyntaxKind.FalseLiteralExpression))
                        .WithNameEquals(NameEquals("Inherited")),
                ])))));
    }

    private static string AttributeType(JsonElement schema)
    {
        if (schema.TryGetProperty("$ref", out JsonElement reference))
        {
            throw new InvalidOperationException($"CLR attributes cannot expose referenced schema type '{reference.GetString()}'.");
        }

        if (schema.TryGetProperty("type", out JsonElement type))
        {
            return type.GetString() switch
            {
                "string" => "string",
                "boolean" => "bool",
                "integer" => "int",
                "array" when schema.GetProperty("items").GetProperty("type").GetString() == "string" => "string[]",
                _ => throw new InvalidOperationException($"Unsupported CLR attribute field schema: {schema.GetRawText()}"),
            };
        }

        throw new InvalidOperationException($"Unsupported CLR attribute field schema: {schema.GetRawText()}");
    }

    private static string ExplicitAttributeType(JsonElement type) => type.ValueKind switch
    {
        JsonValueKind.String => AttributeType(type.GetString()!),
        JsonValueKind.Object when type.TryGetProperty("clr", out JsonElement clr) => clr.GetString()!,
        _ => throw new InvalidOperationException($"Unsupported CLR attribute type descriptor '{type.GetRawText()}'."),
    };

    private static string AttributeType(string type) => type switch
    {
        "string" => "string",
        "boolean" => "bool",
        "integer" => "int",
        "string[]" => "string[]",
        _ => throw new InvalidOperationException($"Unsupported synthetic CLR attribute type '{type}'."),
    };

    private static string Pascal(string value) =>
        value.Length == 0 ? value : char.ToUpperInvariant(value[0]) + value[1..];
}