/** Bidirectional lookup, so one table serves both singular -> plural and plural -> singular. */
class Bidirectional {
  private readonly forward = new Map<string, string>();
  private readonly backward = new Map<string, string>();

  constructor(entries: Readonly<Record<string, string>> = {}) {
    for (const [key, value] of Object.entries(entries)) this.add(key, value);
  }

  add(first: string, second: string): void {
    this.forward.set(first, second);
    this.backward.set(second, first);
  }

  hasSingular(word: string): boolean {
    return this.forward.has(word);
  }

  hasPlural(word: string): boolean {
    return this.backward.has(word);
  }

  toSingular(word: string): string {
    const value = this.backward.get(word);
    if (value === undefined) throw new Error(`Cannot find key '${word}'.`);
    return value;
  }
}

const endsWithIgnoreCase = (word: string, suffix: string): boolean =>
  word.toLowerCase().endsWith(suffix.toLowerCase());

const hasAnySuffix = (word: string, suffixes: readonly string[]): boolean =>
  suffixes.some((suffix) => endsWithIgnoreCase(word, suffix));

/** Applies `inflect` only when one of `suffixes` matches, else undefined so the caller falls through. */
function inflectOnSuffix(
  word: string,
  suffixes: readonly string[],
  inflect: (word: string) => string,
): string | undefined {
  return hasAnySuffix(word, suffixes) ? inflect(word) : undefined;
}

