const isCapitalized = (word: string): boolean => word !== "" && word.charAt(0) === word.charAt(0).toUpperCase();

/**
 * False for empty, padded, or non-alphabetic words -- those are left alone. The `\\s` is upstream's
 * escaping slip, kept: it admits a literal backslash instead of whitespace, so a spaced phrase is
 * "non-alphabetic" and returns unchanged. `singularize` splits on `deconstruct` first, so no word
 * reaching here contains a space either way.
 */
const isAlphabetic = (word: string): boolean =>
  word !== "" && word === word.trim() && !/[^a-zA-Z\\s]/.test(word);

const isNoOpWord = (word: string): boolean =>
  !isAlphabetic(word) || word.length <= 1 || pronounList.includes(word.toLowerCase());

const isUninflective = (word: string): boolean =>
  hasAnySuffix(word, uninflectiveSuffixList) ||
  (word.toLowerCase() !== word && word.endsWith("ese")) ||
  uninflectiveWordList.includes(word.toLowerCase());

/** Splits on the last space, since only the final word inflects. */
function splitSuffix(word: string): { prefix: string; suffix: string } {
  const lastSpace = word.lastIndexOf(" ");
  return { prefix: word.slice(0, lastSpace + 1), suffix: word.slice(lastSpace + 1) };
}

function capitalizeLike(word: string, inflect: (word: string) => string): string {
  const result = inflect(word);
  if (!isCapitalized(word) || result.length === 0) return result;
  return result.charAt(0).toUpperCase() + result.slice(1);
}

function singularizeWord(word: string): string {
  if (userDictionary.hasPlural(word)) return userDictionary.toSingular(word);
  if (isNoOpWord(word)) return word;

  const { prefix, suffix } = splitSuffix(word);
  if (isNoOpWord(suffix)) return prefix + suffix;
  if (isUninflective(suffix)) return prefix + suffix;
  if (knownSingularWords.includes(suffix.toLowerCase())) return prefix + suffix;

  if (irregularVerbs.hasPlural(suffix)) return prefix + irregularVerbs.toSingular(suffix);
  if (irregularPlurals.hasPlural(suffix)) return prefix + irregularPlurals.toSingular(suffix);
  if (wordsEndingWithSis.hasPlural(suffix)) return prefix + wordsEndingWithSis.toSingular(suffix);
  if (wordsEndingWithSe.hasPlural(suffix)) return prefix + wordsEndingWithSe.toSingular(suffix);
  if (wordsEndingWithSus.hasPlural(suffix)) return prefix + wordsEndingWithSus.toSingular(suffix);

  // Ordered as upstream: earlier rules would otherwise be shadowed by later, broader ones.
  const rules: readonly [readonly string[], (word: string) => string][] = [
    [["men"], (s) => `${s.slice(0, -2)}an`],
    [["lice", "mice"], (s) => `${s.slice(0, -3)}ouse`],
    [["teeth"], (s) => `${s.slice(0, -4)}ooth`],
    [["geese"], (s) => `${s.slice(0, -4)}oose`],
    [["feet"], (s) => `${s.slice(0, -3)}oot`],
    [["zoa"], (s) => `${s.slice(0, -2)}oon`],
    [["ches", "shes", "sses"], (s) => s.slice(0, -2)],
  ];
  for (const [suffixes, inflect] of rules) {
    const inflected = inflectOnSuffix(suffix, suffixes, inflect);
    if (inflected !== undefined) return prefix + inflected;
  }

  if (assimilatedClassicalInflection.hasPlural(suffix)) {
    return prefix + assimilatedClassicalInflection.toSingular(suffix);
  }
  if (classicalInflection.hasPlural(suffix)) return prefix + classicalInflection.toSingular(suffix);

  const trices = inflectOnSuffix(suffix, ["trices"], (s) => `${s.slice(0, -3)}x`);
  if (trices !== undefined) return prefix + trices;

  const eaux = inflectOnSuffix(suffix, ["eaux", "ieux"], (s) => s.slice(0, -1));
  if (eaux !== undefined) return prefix + eaux;

  if (wordsEndingWithInxAnxYnx.hasPlural(suffix)) {
    return prefix + wordsEndingWithInxAnxYnx.toSingular(suffix);
  }

  const ves = inflectOnSuffix(suffix, ["alves", "elves", "olves", "eaves", "arves"], (s) => `${s.slice(0, -3)}f`);
  if (ves !== undefined) return prefix + ves;

  const ives = inflectOnSuffix(suffix, ["nives", "lives", "wives"], (s) => `${s.slice(0, -3)}fe`);
  if (ives !== undefined) return prefix + ives;

  const vowelY = inflectOnSuffix(suffix, ["ays", "eys", "iys", "oys", "uys"], (s) => s.slice(0, -1));
  if (vowelY !== undefined) return prefix + vowelY;

  if (endsWithIgnoreCase(suffix, "ies")) return `${prefix}${suffix.slice(0, -3)}y`;

  if (oSuffix.hasPlural(suffix)) return prefix + oSuffix.toSingular(suffix);

  const vowelO = inflectOnSuffix(suffix, ["aos", "eos", "ios", "oos", "uos"], (s) => s.slice(0, -1));
  if (vowelO !== undefined) return prefix + vowelO;

  const ces = inflectOnSuffix(suffix, ["ces"], (s) => s.slice(0, -1));
  if (ces !== undefined) return prefix + ces;

  const ses = inflectOnSuffix(suffix, ["ces", "ses", "xes"], (s) => s.slice(0, -2));
  if (ses !== undefined) return prefix + ses;

  if (endsWithIgnoreCase(suffix, "oes")) return prefix + suffix.slice(0, -2);
  if (endsWithIgnoreCase(suffix, "ss")) return prefix + suffix;
  if (endsWithIgnoreCase(suffix, "s")) return prefix + suffix.slice(0, -1);

  return prefix + suffix;
}

/**
 * Singularizes an identifier: only the final word inflects, and the result is re-cased through
 * `pascalCase` -- which is where `vm` becomes `VM`.
 */
export function singularize(word: string): string {
  if (!word) return word;
  const words = [...deconstruct(word)];
  // Upstream indexes the last element unguarded; a name with no word characters would throw there.
  if (words.length === 0) return word;
  words[words.length - 1] = capitalizeLike(words[words.length - 1]!, singularizeWord);
  return pascalCase(words);
}
